// FetchCertificateAuthorityCsr is the CSR of a CA "in state
// AWAITING_USER_ACTIVATION", signed by its key, with its subject and
// extensions.
func (a *API) FetchCertificateAuthorityCsr(_ context.Context, req *privatecapb.FetchCertificateAuthorityCsrRequest) (*privatecapb.FetchCertificateAuthorityCsrResponse, error) {
	s := a.s
	s.mu.Lock()
	defer s.mu.Unlock()
	c, err := s.ca(req.GetName())
	if err != nil {
		return nil, err
	}
	if c.CA.GetState() != privatecapb.CertificateAuthority_AWAITING_USER_ACTIVATION {
		return nil, wrongState(c.CA, "fetch the CSR of", privatecapb.CertificateAuthority_AWAITING_USER_ACTIVATION)
	}
	return &privatecapb.FetchCertificateAuthorityCsrResponse{PemCsr: c.CSR}, nil
}

// makeCSR is the CSR of a CA awaiting activation: its subject, SANs and
// x509 config as requested extensions.
func makeCSR(rec *caRecord) (string, error) {
	cfg := rec.CA.GetConfig()
	subj, err := subjectName(cfg.GetSubjectConfig().GetSubject())
	if err != nil {
		return "", err
	}
	t := &x509.Certificate{Subject: subj}
	if err := applySANs(t, cfg.GetSubjectConfig().GetSubjectAltName()); err != nil {
		return "", err
	}
	if err := applyX509(t, cfg.GetX509Config()); err != nil {
		return "", err
	}
	// The extensions applyX509 would encode, through a self-signed
	// throwaway certificate, so the CSR asks for exactly them.
	t.SerialNumber, t.NotBefore, t.NotAfter = big.NewInt(1), time.Unix(0, 0), time.Unix(1, 0)
	der, err := x509.CreateCertificate(rand.Reader, t, t, rec.Key.Public(), rec.Key)
	if err != nil {
		return "", apierror.InvalidArgument("the CA's config cannot be encoded: %v", err)
	}
	tmp, _ := x509.ParseCertificate(der)
	var exts []pkix.Extension
	for _, e := range tmp.Extensions {
		if e.Id.Equal(oidSubjectKeyID) || e.Id.Equal(oidAuthorityKeyID) {
			continue
		}
		exts = append(exts, e)
	}
	csr, err := x509.CreateCertificateRequest(rand.Reader, &x509.CertificateRequest{Subject: subj, ExtraExtensions: exts}, rec.Key)
	if err != nil {
		return "", apierror.InvalidArgument("the CSR cannot be made: %v", err)
	}
	return string(pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE REQUEST", Bytes: csr})), nil
}

var (
	oidSubjectKeyID   = asn1.ObjectIdentifier{2, 5, 29, 14}
	oidAuthorityKeyID = asn1.ObjectIdentifier{2, 5, 29, 35}
)

// csrCA is the CA awaiting activation whose key a CSR carries, so its
// requested CA extensions are honoured when an issuing CA signs it; nil
// for any other CSR. The caller holds mu.
func (s *Server) csrCA(csr *x509.CertificateRequest) *caRecord {
	for _, c := range s.cas {
		if c.CA.GetState() != privatecapb.CertificateAuthority_AWAITING_USER_ACTIVATION {
			continue
		}
		if k, ok := c.Key.Public().(interface{ Equal(crypto.PublicKey) bool }); ok && k.Equal(csr.PublicKey) {
			return c
		}
	}
	return nil
}

// ActivateCertificateAuthority activates "a CertificateAuthority that is
// in state AWAITING_USER_ACTIVATION and is of type SUBORDINATE" with the
// certificate its issuer signed from its CSR, and the issuer: a CA of this
// service (subordinate_config.certificate_authority) or a third party's
// chain (pem_issuer_chain). The certificate must hold the CA's key, be a
// CA certificate, and verify against the chain up to its root. The CA is
// then STAGED, as a new root is (UNVERIFIED (docs re-read 2026-11-18:
// <https://docs.cloud.google.com/certificate-authority-service/docs/reference/rest/v1/projects.locations.caPools.certificateAuthorities/activate>
// names no resulting state)).
func (a *API) ActivateCertificateAuthority(_ context.Context, req *privatecapb.ActivateCertificateAuthorityRequest) (*longrunningpb.Operation, error) {
	s := a.s
	if strings.TrimSpace(req.GetPemCaCertificate()) == "" {
		return nil, apierror.InvalidArgument("pem_ca_certificate is required")
	}
	if req.GetSubordinateConfig() == nil {
		return nil, apierror.InvalidArgument("subordinate_config is required")
	}
	s.mu.Lock()
	defer s.mu.Unlock()
	c, err := s.ca(req.GetName())
	if err != nil {
		return nil, err
	}
	if c.CA.GetType() != privatecapb.CertificateAuthority_SUBORDINATE || c.CA.GetState() != privatecapb.CertificateAuthority_AWAITING_USER_ACTIVATION {
		return nil, apierror.FailedPrecondition("CertificateAuthority %s is %s %s; only a SUBORDINATE CA AWAITING_USER_ACTIVATION is activated",
			req.GetName(), c.CA.GetType(), c.CA.GetState())
	}
	cert, err := parsePEMCert(req.GetPemCaCertificate())
	if err != nil {
		return nil, apierror.InvalidArgument("pem_ca_certificate: %v", err)
	}
	if k, ok := c.Key.Public().(interface{ Equal(crypto.PublicKey) bool }); !ok || !k.Equal(cert.PublicKey) {
		return nil, apierror.InvalidArgument("pem_ca_certificate does not certify this CertificateAuthority's key: sign the CSR FetchCertificateAuthorityCsr returns")
	}
	if !cert.BasicConstraintsValid || !cert.IsCA {
		return nil, apierror.InvalidArgument("pem_ca_certificate is not a CA certificate (basic constraints CA:TRUE)")
	}
	var chain []string
	switch sc := req.GetSubordinateConfig().GetSubordinateConfig().(type) {
	case *privatecapb.SubordinateConfig_CertificateAuthority:
		issuer, err := s.ca(sc.CertificateAuthority)
		if err != nil {
			return nil, err
		}
		chain = issuer.CA.GetPemCaCertificates()
	case *privatecapb.SubordinateConfig_PemIssuerChain:
		chain = sc.PemIssuerChain.GetPemCertificates()
	default:
		return nil, apierror.InvalidArgument("subordinate_config needs certificate_authority or pem_issuer_chain")
	}
	if len(chain) == 0 {
		return nil, apierror.InvalidArgument("subordinate_config: the issuer chain is empty")
	}
	inter, roots := x509.NewCertPool(), x509.NewCertPool()
	for i, p := range chain {
		ic, err := parsePEMCert(p)
		if err != nil {
			return nil, apierror.InvalidArgument("pem_issuer_chain[%d]: %v", i, err)
		}
		if i == len(chain)-1 {
			roots.AddCert(ic)
		} else {
			inter.AddCert(ic)
		}
	}
	if _, err := cert.Verify(x509.VerifyOptions{Roots: roots, Intermediates: inter, CurrentTime: s.now(),
		KeyUsages: []x509.ExtKeyUsage{x509.ExtKeyUsageAny}}); err != nil {
		return nil, apierror.InvalidArgument("pem_ca_certificate does not verify against the issuer chain: %v", err)
	}
	next := clone(c.CA)
	next.SubordinateConfig = clone(req.GetSubordinateConfig())
	next.PemCaCertificates = append([]string{pemCert(cert.Raw)}, chain...)
	next.CaCertificateDescriptions = []*privatecapb.CertificateDescription{describe(cert)}
	next.State = privatecapb.CertificateAuthority_STAGED
	next.UpdateTime = timestamppb.New(s.now())
	c.CA, c.Cert, c.CSR = next, cert, ""
	next.AccessUrls = s.accessURLs(next)
	if err := s.regenCRL(next.GetName()); err != nil {
		return nil, err
	}
	loc, _, _ := strings.Cut(req.GetName(), "/caPools/")
	return s.done(loc, "activate", req.GetName(), clone(next))
}

// ---- Certificate templates ----

func (s *Server) template(name string) (*templateRecord, error) {
	if !templateRE.MatchString(name) {
		return nil, apierror.InvalidArgument("name %q must be projects/{project}/locations/{location}/certificateTemplates/{certificate_template}", name)
	}
	t, ok := s.templates[name]
	if !ok {
		return nil, apierror.NotFound("CertificateTemplate %s not found", name)
	}
	return t, nil
}

// checkTemplate refuses what a template holds that is not served.
func checkTemplate(t *privatecapb.CertificateTemplate) error {
	if t.GetIdentityConstraints().GetCelExpression().GetExpression() != "" {
		return apierror.Unimplemented("identity_constraints.cel_expression is not implemented in CloudBurrow yet")
	}
	if pe := t.GetPassthroughExtensions(); len(pe.GetKnownExtensions()) > 0 || len(pe.GetAdditionalExtensions()) > 0 {
		return apierror.Unimplemented("passthrough_extensions is not implemented in CloudBurrow yet: no CSR extension is copied")
	}
	if t.GetPredefinedValues().GetCaOptions().GetIsCa() {
		// Allowed, as Google allows a template that issues CA certificates.
		return nil
	}
	return nil
}

func (a *API) CreateCertificateTemplate(_ context.Context, req *privatecapb.CreateCertificateTemplateRequest) (*longrunningpb.Operation, error) {
	if err := checkLocation("parent", req.GetParent()); err != nil {
		return nil, err
	}
	if err := checkID("certificate_template_id", req.GetCertificateTemplateId()); err != nil {
		return nil, err
	}
	in := req.GetCertificateTemplate()
	if in == nil {
		return nil, apierror.InvalidArgument("certificate_template is required")
	}
	if err := checkTemplate(in); err != nil {
		return nil, err
	}
	s := a.s
	s.mu.Lock()
	defer s.mu.Unlock()
	name := req.GetParent() + "/certificateTemplates/" + req.GetCertificateTemplateId()
	if _, ok := s.templates[name]; ok {
		return nil, apierror.AlreadyExists("CertificateTemplate %s already exists", name)
	}
	rec := clone(in)
	rec.Name = name
	rec.CreateTime = timestamppb.New(s.now())
	rec.UpdateTime = rec.CreateTime
	s.templates[name] = &templateRecord{Template: rec}
	return s.done(req.GetParent(), "create", name, rec)
}

