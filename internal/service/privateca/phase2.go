// Phase 2 of #1834: subordinate CAs (FetchCertificateAuthorityCsr and
// ActivateCertificateAuthority), certificate templates, and certificate
// revocation lists, generated by the CA's key and published, with its CA
// certificate, at the access URLs the CA reports, served by this port.

var (
	templateRE = regexp.MustCompile(`^(projects/[^/]+/locations/[^/]+)/certificateTemplates/([^/]+)$`)
	crlRE      = regexp.MustCompile(`^(projects/[^/]+/locations/[^/]+/caPools/[^/]+/certificateAuthorities/[^/]+)/certificateRevocationLists/([^/]+)$`)
)

// CRLValidity is how long a CRL is valid after it is generated (its
// nextUpdate). UNVERIFIED (docs re-read 2026-11-18:
// <https://docs.cloud.google.com/certificate-authority-service/docs/revoking-certificates>
// says a revoked certificate appears "in all future CRLs until the
// certificate reaches its expiry date" and states no CRL lifetime): 7 days.
const CRLValidity = 7 * 24 * time.Hour

// templateRecord is a certificate template and its IAM policy.
type templateRecord struct {
	Template *privatecapb.CertificateTemplate
	Policy   *iampolicy.Stored
}

// SetAddress gives the server the address its content (CA certificates
// and CRLs) is published at, host:port of this port.
func (s *Server) SetAddress(addr func() string) { s.addr = addr }

// contentBase is the URL a CA's published content is under, or "" when
// the server has no address.
func (s *Server) contentBase(caName string) string {
	if s.addr == nil || s.addr() == "" {
		return ""
	}
	return "http://" + s.addr() + "/privateca-content/" + caName
}

// accessURLs are the URLs a CA's pool publishes its content at:
// "caCertificateAccessUrl: The URL where this CertificateAuthority's CA
// certificate is published", and crlAccessUrls "will only be set for CAs
// that have been activated". The caller holds mu.
func (s *Server) accessURLs(ca *privatecapb.CertificateAuthority) *privatecapb.CertificateAuthority_AccessUrls {
	out := &privatecapb.CertificateAuthority_AccessUrls{}
	pool, _, _ := strings.Cut(ca.GetName(), "/certificateAuthorities/")
	p, ok := s.pools[pool]
	base := s.contentBase(ca.GetName())
	if !ok || base == "" {
		return out
	}
	opts := p.Pool.GetPublishingOptions()
	if opts.GetPublishCaCert() && len(ca.GetPemCaCertificates()) > 0 {
		out.CaCertificateAccessUrl = base + "/ca.crt"
	}
	if opts.GetPublishCrl() && ca.GetState() != privatecapb.CertificateAuthority_AWAITING_USER_ACTIVATION {
		out.CrlAccessUrls = []string{base + "/crl.crl"}
	}
	return out
}

// refreshAccessURLs sets every CA of pool's access URLs; the caller holds
// mu.
func (s *Server) refreshAccessURLs(pool string) {
	for _, k := range sortedKeys(s.cas, pool+"/certificateAuthorities/") {
		c := s.cas[k]
		next := clone(c.CA)
		next.AccessUrls = s.accessURLs(next)
		c.CA = next
	}
}

// publishTo sets an issued certificate's AIA and CRL distribution point
// from the issuer's access URLs, as Google's published content is named
// in the certificates the CA issues.
func publishTo(t *x509.Certificate, issuer *privatecapb.CertificateAuthority) {
	u := issuer.GetAccessUrls()
	if u.GetCaCertificateAccessUrl() != "" {
		t.IssuingCertificateURL = []string{u.GetCaCertificateAccessUrl()}
	}
	t.CRLDistributionPoints = append(t.CRLDistributionPoints, u.GetCrlAccessUrls()...)
}

// ---- Content ----

// contentHandler serves /privateca-content/{ca}/ca.crt and crl.crl, in
// the pool's publishing encoding (PEM unless DER), only while the pool
// publishes them.
func (s *Server) contentHandler(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		rest, ok := strings.CutPrefix(r.URL.Path, "/privateca-content/")
		if !ok {
			next.ServeHTTP(w, r)
			return
		}
		if r.Method != http.MethodGet && r.Method != http.MethodHead {
			http.Error(w, "method not allowed", http.StatusMethodNotAllowed)
			return
		}
		i := strings.LastIndex(rest, "/")
		if i < 0 {
			http.NotFound(w, r)
			return
		}
		caName, file := rest[:i], rest[i+1:]
		body, ctype, ok := s.content(caName, file)
		if !ok {
			http.NotFound(w, r)
			return
		}
		w.Header().Set("Content-Type", ctype)
		w.Header().Set("Content-Length", strconv.Itoa(len(body)))
		_, _ = w.Write(body)
	})
}

func (s *Server) content(caName, file string) ([]byte, string, bool) {
	s.mu.Lock()
	defer s.mu.Unlock()
	c, ok := s.cas[caName]
	if !ok {
		return nil, "", false
	}
	u := c.CA.GetAccessUrls()
	pool, _, _ := strings.Cut(caName, "/certificateAuthorities/")
	asDER := s.pools[pool] != nil && s.pools[pool].Pool.GetPublishingOptions().GetEncodingFormat() == privatecapb.CaPool_PublishingOptions_DER
	switch file {
	case "ca.crt":
		if u.GetCaCertificateAccessUrl() == "" || c.Cert == nil {
			return nil, "", false
		}
		if asDER {
			return c.Cert.Raw, "application/pkix-cert", true
		}
		return []byte(c.CA.GetPemCaCertificates()[0]), "application/x-pem-file", true
	case "crl.crl":
		if len(u.GetCrlAccessUrls()) == 0 {
			return nil, "", false
		}
		crl := s.crls[s.crlFor(caName)]
		if crl == nil {
			return nil, "", false
		}
		if asDER {
			blk, _ := pem.Decode([]byte(crl.GetPemCrl()))
			if blk == nil {
				return nil, "", false
			}
			return blk.Bytes, "application/pkix-crl", true
		}
		return []byte(crl.GetPemCrl()), "application/x-pem-file", true
	}
	return nil, "", false
}

// ---- CRLs ----

// crlFor is the name of a CA's CRL resource, or "". The caller holds mu.
func (s *Server) crlFor(caName string) string {
	keys := sortedKeys(s.crls, caName+"/certificateRevocationLists/")
	if len(keys) == 0 {
		return ""
	}
	return keys[len(keys)-1]
}

// crlReason is RFC 5280's CRLReason for a RevocationReason.
func crlReason(r privatecapb.RevocationReason) int {
	switch r {
	case privatecapb.RevocationReason_PRIVILEGE_WITHDRAWN:
		return 9
	case privatecapb.RevocationReason_ATTRIBUTE_AUTHORITY_COMPROMISE:
		return 10
	}
	return int(r)
}

// regenCRL generates a CA's CRL: "ENABLED, STAGED: CRLs will be
// generated for this CA", every unexpired certificate it revoked, signed
// by its key. The CA keeps one CertificateRevocationList resource, whose
// sequence_number and revision_id change with each generation
// (UNVERIFIED (docs re-read 2026-11-18:
// <https://docs.cloud.google.com/certificate-authority-service/docs/reference/rest/v1/projects.locations.caPools.certificateAuthorities.certificateRevocationLists>):
// how Google names CRL resources). The caller holds mu.
func (s *Server) regenCRL(caName string) error {
	c, ok := s.cas[caName]
	if !ok || c.Cert == nil {
		return nil
	}
	switch c.CA.GetState() {
	case privatecapb.CertificateAuthority_ENABLED, privatecapb.CertificateAuthority_STAGED, privatecapb.CertificateAuthority_DISABLED:
	default:
		return nil
	}
	if c.Cert.KeyUsage != 0 && c.Cert.KeyUsage&x509.KeyUsageCRLSign == 0 {
		// The CA's certificate does not allow it to sign CRLs.
		return nil
	}
	now := s.now()
	name := s.crlFor(caName)
	prev := s.crls[name]
	seq := int64(1)
	if prev != nil {
		seq = prev.GetSequenceNumber() + 1
	} else {
		name = caName + "/certificateRevocationLists/" + now.UTC().Format("20060102") + "-" + randomHex(4)
	}
	pool, _, _ := strings.Cut(caName, "/certificateAuthorities/")
	var entries []x509.RevocationListEntry
	var revoked []*privatecapb.CertificateRevocationList_RevokedCertificate
	for _, k := range sortedKeys(s.certs, pool+"/certificates/") {
		crt := s.certs[k]
		rd := crt.GetRevocationDetails()
		if crt.GetIssuerCertificateAuthority() != caName || rd == nil ||
			!now.Before(crt.GetCertificateDescription().GetSubjectDescription().GetNotAfterTime().AsTime()) {
			continue
		}
		sn, ok := new(big.Int).SetString(crt.GetCertificateDescription().GetSubjectDescription().GetHexSerialNumber(), 16)
		if !ok {
			continue
		}
		entries = append(entries, x509.RevocationListEntry{SerialNumber: sn, RevocationTime: rd.GetRevocationTime().AsTime(),
			ReasonCode: crlReason(rd.GetRevocationState())})
		revoked = append(revoked, &privatecapb.CertificateRevocationList_RevokedCertificate{Certificate: k,
			HexSerialNumber: crt.GetCertificateDescription().GetSubjectDescription().GetHexSerialNumber(), RevocationReason: rd.GetRevocationState()})
	}
	der, err := x509.CreateRevocationList(rand.Reader, &x509.RevocationList{Number: big.NewInt(seq), ThisUpdate: now,
		NextUpdate: now.Add(CRLValidity), RevokedCertificateEntries: entries}, c.Cert, c.Key)
	if err != nil {
		return apierror.Internal(err, "generate the CRL of %s", caName)
	}
	out := &privatecapb.CertificateRevocationList{Name: name, SequenceNumber: seq,
		RevokedCertificates: revoked, PemCrl: string(pem.EncodeToMemory(&pem.Block{Type: "X509 CRL", Bytes: der})),
		State: privatecapb.CertificateRevocationList_ACTIVE, RevisionId: randomHex(4), UpdateTime: timestamppb.New(now)}
	if prev != nil {
		out.CreateTime, out.Labels = prev.GetCreateTime(), prev.GetLabels()
	} else {
		out.CreateTime = out.UpdateTime
	}
	if urls := c.CA.GetAccessUrls().GetCrlAccessUrls(); len(urls) > 0 {
		out.AccessUrl = urls[0]
	}
	s.crls[name] = out
	return nil
}

func (s *Server) crl(name string) (*privatecapb.CertificateRevocationList, error) {
	if !crlRE.MatchString(name) {
		return nil, apierror.InvalidArgument("name %q must be projects/{project}/locations/{location}/caPools/{ca_pool}/certificateAuthorities/{certificate_authority}/certificateRevocationLists/{certificate_revocation_list}", name)
	}
	c, ok := s.crls[name]
	if !ok {
		return nil, apierror.NotFound("CertificateRevocationList %s not found", name)
	}
	return c, nil
}

func (a *API) GetCertificateRevocationList(_ context.Context, req *privatecapb.GetCertificateRevocationListRequest) (*privatecapb.CertificateRevocationList, error) {
	a.s.mu.Lock()
	defer a.s.mu.Unlock()
	c, err := a.s.crl(req.GetName())
	if err != nil {
		return nil, err
	}
	return clone(c), nil
}

func (a *API) ListCertificateRevocationLists(_ context.Context, req *privatecapb.ListCertificateRevocationListsRequest) (*privatecapb.ListCertificateRevocationListsResponse, error) {
	if err := refuseFilter(req.GetFilter(), req.GetOrderBy()); err != nil {
		return nil, err
	}
	s := a.s
	s.mu.Lock()
	defer s.mu.Unlock()
	if !caRE.MatchString(req.GetParent()) {
		return nil, apierror.InvalidArgument("parent %q must be a CertificateAuthority name", req.GetParent())
	}
	out, next, err := page("privateca-crls:"+req.GetParent(), sortedKeys(s.crls, req.GetParent()+"/certificateRevocationLists/"), req.GetPageToken(), req.GetPageSize(),
		func(k string) *privatecapb.CertificateRevocationList { return clone(s.crls[k]) })
	if err != nil {
		return nil, err
	}
	return &privatecapb.ListCertificateRevocationListsResponse{CertificateRevocationLists: out, NextPageToken: next}, nil
}

// UpdateCertificateRevocationList updates labels, the one field of a CRL
// that is not output only.
func (a *API) UpdateCertificateRevocationList(_ context.Context, req *privatecapb.UpdateCertificateRevocationListRequest) (*longrunningpb.Operation, error) {
	in := req.GetCertificateRevocationList()
	paths := req.GetUpdateMask().GetPaths()
	if in == nil || len(paths) == 0 {
		return nil, apierror.InvalidArgument("certificate_revocation_list and update_mask are required")
	}
	s := a.s
	s.mu.Lock()
	defer s.mu.Unlock()
	c, err := s.crl(in.GetName())
	if err != nil {
		return nil, err
	}
	next := clone(c)
	for _, p := range paths {
		if p != "labels" {
			return nil, apierror.InvalidArgument("update_mask path %q cannot be updated: only labels can", p)
		}
		next.Labels = in.GetLabels()
	}
	next.UpdateTime = timestamppb.New(s.now())
	s.crls[in.GetName()] = next
	loc, _, _ := strings.Cut(in.GetName(), "/caPools/")
	return s.done(loc, "update", in.GetName(), next)
}

