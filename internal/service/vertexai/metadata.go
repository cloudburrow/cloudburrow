// sameStore checks that name is a coll node of store.
func sameStore(field, coll, store, name string) error {
	s, _, err := parseMDName(field, coll, name)
	if err != nil {
		return err
	}
	if s != store {
		return apierror.InvalidArgument("%s %q is not in MetadataStore %s", field, name, store)
	}
	return nil
}

func (m *metadataService) AddContextArtifactsAndExecutions(_ context.Context, req *aiplatformpb.AddContextArtifactsAndExecutionsRequest) (*aiplatformpb.AddContextArtifactsAndExecutionsResponse, error) {
	st := m.s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	ctx := req.GetContext()
	if _, err := mdLookup(st, contextKind, "context", ctx); err != nil {
		return nil, grpcError(err)
	}
	store, _, _ := parseMDName("context", "contexts", ctx)
	md := st.meta()
	for _, a := range req.GetArtifacts() {
		if err := sameStore("artifacts", "artifacts", store, a); err != nil {
			return nil, grpcError(err)
		}
		if md.artifacts[a] == nil {
			return nil, grpcError(apierror.NotFound("Artifact %s not found", a))
		}
	}
	for _, e := range req.GetExecutions() {
		if err := sameStore("executions", "executions", store, e); err != nil {
			return nil, grpcError(err)
		}
		if md.executions[e] == nil {
			return nil, grpcError(apierror.NotFound("Execution %s not found", e))
		}
	}
	add := func(m map[string]map[string]bool, names []string) {
		if len(names) == 0 {
			return
		}
		if m[ctx] == nil {
			m[ctx] = map[string]bool{}
		}
		for _, n := range names {
			m[ctx][n] = true
		}
	}
	add(md.ctxArtifacts, req.GetArtifacts())
	add(md.ctxExecutions, req.GetExecutions())
	st.save()
	return &aiplatformpb.AddContextArtifactsAndExecutionsResponse{}, nil
}

// isAncestor reports whether a is c or one of c's ancestors.
func (md *mdStore) isAncestor(a, c string, seen map[string]bool) bool {
	if a == c {
		return true
	}
	if seen[c] {
		return false
	}
	seen[c] = true
	for _, p := range md.contexts[c].GetParentContexts() {
		if md.isAncestor(a, p, seen) {
			return true
		}
	}
	return false
}

func (m *metadataService) AddContextChildren(_ context.Context, req *aiplatformpb.AddContextChildrenRequest) (*aiplatformpb.AddContextChildrenResponse, error) {
	st := m.s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	parent := req.GetContext()
	if _, err := mdLookup(st, contextKind, "context", parent); err != nil {
		return nil, grpcError(err)
	}
	store, _, _ := parseMDName("context", "contexts", parent)
	md := st.meta()
	for _, c := range req.GetChildContexts() {
		if err := sameStore("child_contexts", "contexts", store, c); err != nil {
			return nil, grpcError(err)
		}
		child := md.contexts[c]
		if child == nil {
			return nil, grpcError(apierror.NotFound("Context %s not found", c))
		}
		if md.isAncestor(c, parent, map[string]bool{}) {
			return nil, grpcError(apierror.InvalidArgument("adding Context %s as a child of %s would create a cycle", c, parent))
		}
	}
	changed := false
	for _, c := range req.GetChildContexts() {
		child := md.contexts[c]
		has := false
		for _, p := range child.GetParentContexts() {
			has = has || p == parent
		}
		if has {
			continue
		}
		if len(child.GetParentContexts()) >= mdMaxParents {
			return nil, grpcError(apierror.InvalidArgument("Context %s would have more than %d parent Contexts", c, mdMaxParents))
		}
		child.ParentContexts = append(child.ParentContexts, parent)
		changed = true
	}
	if changed {
		st.save()
	}
	return &aiplatformpb.AddContextChildrenResponse{}, nil
}

