// storeView is a store with its disk use; the caller holds st.mu.
func (st *notebookStore) storeView(s *aiplatformpb.MetadataStore) *aiplatformpb.MetadataStore {
	out := proto.Clone(s).(*aiplatformpb.MetadataStore)
	md, prefix := st.meta(), s.GetName()+"/"
	var n int
	add := func(name string, m proto.Message) {
		if strings.HasPrefix(name, prefix) {
			n += proto.Size(m)
		}
	}
	for k, v := range md.artifacts {
		add(k, v)
	}
	for k, v := range md.contexts {
		add(k, v)
	}
	for k, v := range md.executions {
		add(k, v)
	}
	for k, v := range md.schemas {
		add(k, v)
	}
	for k, evs := range md.events {
		for _, e := range evs {
			add(k, e)
		}
	}
	out.State = &aiplatformpb.MetadataStore_MetadataStoreState{DiskUtilizationBytes: int64(n)}
	return out
}

