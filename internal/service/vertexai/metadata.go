var (
	mdIDRE            = regexp.MustCompile(`^[a-z0-9-]{4,128}$`)
	mdSchemaVersionRE = regexp.MustCompile(`^[0-9]+.+.+$`)
)

const (
	// mdMaxBytes is the quotas page's limit on a resource's metadata and on
	// a metadata schema.
	mdMaxBytes = 204800
	// mdMaxGraph is the lineage queries' limit on each kind of node.
	mdMaxGraph = 1000
	// mdMaxParents is a context's limit on parents.
	mdMaxParents = 10
)

// mdStore is the ML Metadata of every store, by resource name.
type mdStore struct {
	stores     map[string]*aiplatformpb.MetadataStore
	artifacts  map[string]*aiplatformpb.Artifact
	contexts   map[string]*aiplatformpb.Context
	executions map[string]*aiplatformpb.Execution
	schemas    map[string]*aiplatformpb.MetadataSchema
	// events are each execution's, in the order added.
	events map[string][]*aiplatformpb.Event
	// ctxArtifacts and ctxExecutions are each context's attributions and
	// associations.
	ctxArtifacts  map[string]map[string]bool
	ctxExecutions map[string]map[string]bool
}

func newMDStore() *mdStore {
	return &mdStore{stores: map[string]*aiplatformpb.MetadataStore{}, artifacts: map[string]*aiplatformpb.Artifact{},
		contexts: map[string]*aiplatformpb.Context{}, executions: map[string]*aiplatformpb.Execution{},
		schemas: map[string]*aiplatformpb.MetadataSchema{}, events: map[string][]*aiplatformpb.Event{},
		ctxArtifacts: map[string]map[string]bool{}, ctxExecutions: map[string]map[string]bool{}}
}

// meta is the store's ML Metadata; the caller holds st.mu.
func (st *notebookStore) meta() *mdStore {
	if st.md == nil {
		st.md = newMDStore()
	}
	return st.md
}

func (st *notebookStore) clock() time.Time {
	if st.now != nil {
		return st.now()
	}
	return time.Now()
}

// metadataService serves google.cloud.aiplatform.v1.MetadataService.
type metadataService struct {
	aiplatformpb.UnimplementedMetadataServiceServer
	s *Server
}

// defaultMetadataStore returns projects/P/locations/L/metadataStores/default
// for parent "projects/P/locations/L", creating it if absent.
func (s *Server) defaultMetadataStore(parent string) string {
	name := strings.TrimSuffix(parent, "/") + "/metadataStores/default"
	st := s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	_ = st.mdEnsureStore("parent", name)
	return name
}

// mdEnsureStore checks that store exists, making a "default" one on first
// use; the caller holds st.mu.
func (st *notebookStore) mdEnsureStore(field, store string) error {
	if _, _, id, err := parseChild(field, "metadataStores", store); err != nil {
		return err
	} else if _, ok := st.meta().stores[store]; !ok {
		if id != "default" {
			return apierror.NotFound("MetadataStore %s not found", store)
		}
		now := timestamppb.New(st.clock())
		st.meta().stores[store] = &aiplatformpb.MetadataStore{Name: store, CreateTime: now, UpdateTime: now,
			State: &aiplatformpb.MetadataStore_MetadataStoreState{}}
		st.save()
	}
	return nil
}

// parseMDName parses projects/P/locations/L/metadataStores/S/{coll}/{id},
// answering the store's name and the ID.
func parseMDName(field, coll, name string) (string, string, error) {
	p := strings.Split(name, "/")
	if len(p) == 8 && p[0] == "projects" && p[2] == "locations" && p[4] == "metadataStores" && p[6] == coll &&
		p[1] != "" && p[3] != "" && p[5] != "" && p[7] != "" {
		return strings.Join(p[:6], "/"), p[7], nil
	}
	return "", "", apierror.InvalidArgument("%s %q is not projects/{project}/locations/{location}/metadataStores/{metadata_store}/%s/{id}", field, name, coll)
}

func mdPageSize(n int32) (int, error) {
	switch {
	case n < 0 || n > 1000:
		return 0, apierror.InvalidArgument("page_size must be in range 1-1000, got %d", n)
	case n == 0:
		return 100, nil
	}
	return int(n), nil
}

func mdEtag() string { return numericID() }

// ---- the three node kinds, generically

// mdRes is an Artifact, a Context or an Execution.
type mdRes interface {
	proto.Message
	GetName() string
	GetEtag() string
	GetDisplayName() string
	GetLabels() map[string]string
	GetDescription() string
	GetMetadata() *structpb.Struct
}

// mdKind describes one node kind's collection.
type mdKind[T mdRes] struct {
	title, coll, field string
	get                func(*mdStore) map[string]T
	// mutable are the fields an update may change (and an empty mask
	// changes).
	mutable []string
	filter  []string
	// drop removes the node's edges.
	drop func(*mdStore, string)
}

var (
	artifactKind = &mdKind[*aiplatformpb.Artifact]{title: "Artifact", coll: "artifacts", field: "artifact",
		get:     func(m *mdStore) map[string]*aiplatformpb.Artifact { return m.artifacts },
		mutable: []string{"display_name", "uri", "labels", "state", "schema_title", "schema_version", "metadata", "description"},
		filter:  []string{"name", "display_name", "uri", "state", "schema_title", "create_time", "update_time"},
		drop: func(m *mdStore, n string) {
			for e, evs := range m.events {
				m.events[e] = dropEvents(evs, func(ev *aiplatformpb.Event) bool { return ev.GetArtifact() == n })
			}
			for _, set := range m.ctxArtifacts {
				delete(set, n)
			}
		}}
	contextKind = &mdKind[*aiplatformpb.Context]{title: "Context", coll: "contexts", field: "context",
		get:     func(m *mdStore) map[string]*aiplatformpb.Context { return m.contexts },
		mutable: []string{"display_name", "labels", "schema_title", "schema_version", "metadata", "description"},
		filter:  []string{"name", "display_name", "schema_title", "create_time", "update_time"},
		drop: func(m *mdStore, n string) {
			delete(m.ctxArtifacts, n)
			delete(m.ctxExecutions, n)
			for _, c := range m.contexts {
				c.ParentContexts = removeString(c.ParentContexts, n)
			}
		}}
	executionKind = &mdKind[*aiplatformpb.Execution]{title: "Execution", coll: "executions", field: "execution",
		get:     func(m *mdStore) map[string]*aiplatformpb.Execution { return m.executions },
		mutable: []string{"display_name", "state", "labels", "schema_title", "schema_version", "metadata", "description"},
		filter:  []string{"name", "display_name", "state", "schema_title", "create_time", "update_time"},
		drop: func(m *mdStore, n string) {
			delete(m.events, n)
			for _, set := range m.ctxExecutions {
				delete(set, n)
			}
		}}
)

func dropEvents(evs []*aiplatformpb.Event, drop func(*aiplatformpb.Event) bool) []*aiplatformpb.Event {
	out := evs[:0]
	for _, e := range evs {
		if !drop(e) {
			out = append(out, e)
		}
	}
	return out
}

func removeString(in []string, s string) []string {
	out := in[:0]
	for _, v := range in {
		if v != s {
			out = append(out, v)
		}
	}
	if len(out) == 0 {
		return nil
	}
	return out
}

func mdField(m protoreflect.Message, name string) protoreflect.FieldDescriptor {
	return m.Descriptor().Fields().ByName(protoreflect.Name(name))
}

func mdSetString(m proto.Message, name, v string) {
	r := m.ProtoReflect()
	r.Set(mdField(r, name), protoreflect.ValueOfString(v))
}

func mdSetTime(m proto.Message, name string, t time.Time) {
	r := m.ProtoReflect()
	r.Set(mdField(r, name), protoreflect.ValueOfMessage(timestamppb.New(t).ProtoReflect()))
}

// mdCheck validates a node's user fields, trimming its metadata's keys.
func mdCheck(prefix string, r mdRes) error {
	if utf8.RuneCountInString(r.GetDisplayName()) > 128 {
		return apierror.InvalidArgument("%sdisplay_name can be up to 128 Unicode characters long", prefix)
	}
	if err := checkNotebookLabels(r.GetLabels()); err != nil {
		return err
	}
	if st := r.GetMetadata(); st != nil {
		for k, v := range st.GetFields() {
			if t := strings.TrimSpace(k); t != k {
				delete(st.Fields, k)
				st.Fields[t] = v
			}
		}
		if n := proto.Size(st); n > mdMaxBytes {
			return apierror.InvalidArgument("%smetadata is %d bytes; it can be at most %d bytes", prefix, n, mdMaxBytes)
		}
	}
	return nil
}

// mdCreateLocked creates a node; the caller holds st.mu.
func mdCreateLocked[T mdRes](st *notebookStore, k *mdKind[T], parent, id string, in T) (T, error) {
	var zero T
	if err := st.mdEnsureStore("parent", parent); err != nil {
		return zero, err
	}
	if !in.ProtoReflect().IsValid() {
		return zero, apierror.InvalidArgument("%s is required", k.field)
	}
	if id == "" {
		id = uuid.NewString()
	} else if !mdIDRE.MatchString(id) {
		return zero, apierror.InvalidArgument("%s_id %q must be 4-128 characters of lowercase letters, digits and hyphens", k.field, id)
	}
	name := parent + "/" + k.coll + "/" + id
	m := k.get(st.meta())
	if _, ok := m[name]; ok {
		return zero, apierror.AlreadyExists("%s %s already exists", k.title, name)
	}
	c := proto.Clone(in).(T)
	r := c.ProtoReflect()
	for _, f := range []string{"name", "etag", "create_time", "update_time", "parent_contexts"} {
		if fd := mdField(r, f); fd != nil {
			r.Clear(fd)
		}
	}
	if err := mdCheck(k.field+".", c); err != nil {
		return zero, err
	}
	now := st.clock()
	mdSetString(c, "name", name)
	mdSetString(c, "etag", mdEtag())
	mdSetTime(c, "create_time", now)
	mdSetTime(c, "update_time", now)
	m[name] = c
	st.save()
	return proto.Clone(c).(T), nil
}

func mdCreate[T mdRes](s *Server, k *mdKind[T], parent, id string, in T) (T, error) {
	st := s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	out, err := mdCreateLocked(st, k, parent, id, in)
	return out, grpcError(err)
}

// mdLookup finds a node; the caller holds st.mu.
func mdLookup[T mdRes](st *notebookStore, k *mdKind[T], field, name string) (T, error) {
	var zero T
	if _, _, err := parseMDName(field, k.coll, name); err != nil {
		return zero, err
	}
	v, ok := k.get(st.meta())[name]
	if !ok {
		return zero, apierror.NotFound("%s %s not found", k.title, name)
	}
	return v, nil
}

func mdGet[T mdRes](s *Server, k *mdKind[T], name string) (T, error) {
	st := s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	v, err := mdLookup(st, k, "name", name)
	if err != nil {
		var zero T
		return zero, grpcError(err)
	}
	return proto.Clone(v).(T), nil
}

func mdFilterOpts(fields []string) []aipfilter.Option {
	return []aipfilter.Option{aipfilter.Fields(append([]string{"metadata"}, fields...)...)}
}

// mdSelect is a store's nodes of kind k that pass filter, newest first;
// the caller holds st.mu.
func mdSelect[T mdRes](st *notebookStore, k *mdKind[T], parent, filter string) ([]T, error) {
	f, err := st.meta().rewriteFilter(filter, k.coll)
	if err != nil {
		return nil, err
	}
	var all []T
	for n, v := range k.get(st.meta()) {
		if strings.HasPrefix(n, parent+"/"+k.coll+"/") {
			all = append(all, proto.Clone(v).(T))
		}
	}
	sortNewest(all)
	return aipfilter.Apply(f, all, mdFilterOpts(k.filter)...)
}

// sortNewest orders by create_time desc, then name.
func sortNewest[T proto.Message](all []T) {
	ct := func(m T) time.Time {
		r := m.ProtoReflect()
		return r.Get(mdField(r, "create_time")).Message().Interface().(*timestamppb.Timestamp).AsTime()
	}
	nm := func(m T) string { r := m.ProtoReflect(); return r.Get(mdField(r, "name")).String() }
	sort.SliceStable(all, func(i, j int) bool {
		a, b := ct(all[i]), ct(all[j])
		if !a.Equal(b) {
			return a.After(b)
		}
		return nm(all[i]) < nm(all[j])
	})
}

func mdList[T mdRes](s *Server, k *mdKind[T], parent, filter, order, token string, pageSize int32) ([]T, string, error) {
	size, err := mdPageSize(pageSize)
	if err != nil {
		return nil, "", grpcError(err)
	}
	st := s.notebooks()
	st.mu.Lock()
	if err := st.mdEnsureStore("parent", parent); err != nil {
		st.mu.Unlock()
		return nil, "", grpcError(err)
	}
	all, err := mdSelect(st, k, parent, filter)
	st.mu.Unlock()
	if err != nil {
		return nil, "", grpcError(err)
	}
	if err := aipfilter.SortBy(order, all, aipfilter.Fields(append([]string{"schema_version", "description"}, k.filter...)...)); err != nil {
		return nil, "", grpcError(err)
	}
	items, next, err := aipfilter.Page(k.coll+":"+parent+"|"+filter+"|"+order, all, token, size)
	return items, next, grpcError(err)
}

func mdUpdate[T mdRes](s *Server, k *mdKind[T], in T, mask *fieldmaskpb.FieldMask, allowMissing bool) (T, error) {
	var zero T
	if !in.ProtoReflect().IsValid() {
		return zero, grpcError(apierror.InvalidArgument("%s is required", k.field))
	}
	name := in.GetName()
	store, id, err := parseMDName(k.field+".name", k.coll, name)
	if err != nil {
		return zero, grpcError(err)
	}
	paths := k.mutable
	if len(mask.GetPaths()) > 0 {
		paths = nil
		for _, p := range mask.GetPaths() {
			p = camelToSnake(p)
			ok := false
			for _, m := range k.mutable {
				ok = ok || m == p
			}
			if !ok {
				return zero, grpcError(apierror.InvalidArgument("update_mask: %q is not a field of %s that can be updated", p, k.title))
			}
			paths = append(paths, p)
		}
	}
	st := s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	cur, ok := k.get(st.meta())[name]
	if !ok {
		if !allowMissing {
			if err := st.mdEnsureStore(k.field+".name", store); err != nil {
				return zero, grpcError(err)
			}
			return zero, grpcError(apierror.NotFound("%s %s not found", k.title, name))
		}
		out, err := mdCreateLocked(st, k, store, id, in)
		return out, grpcError(err)
	}
	if e := in.GetEtag(); e != "" && e != cur.GetEtag() {
		return zero, grpcError(apierror.FailedPrecondition("%s %s: etag %q does not match its current etag %q", k.title, name, e, cur.GetEtag()))
	}
	c := proto.Clone(cur).(T)
	src, dst := in.ProtoReflect(), c.ProtoReflect()
	for _, p := range paths {
		fd := mdField(dst, p)
		if src.Has(fd) {
			dst.Set(fd, src.Get(fd))
		} else {
			dst.Clear(fd)
		}
	}
	c = proto.Clone(c).(T)
	if err := mdCheck(k.field+".", c); err != nil {
		return zero, grpcError(err)
	}
	mdSetString(c, "etag", mdEtag())
	mdSetTime(c, "update_time", st.clock())
	k.get(st.meta())[name] = c
	st.save()
	return proto.Clone(c).(T), nil
}

func mdDelete[T mdRes](s *Server, k *mdKind[T], name, etag string) (*longrunningpb.Operation, error) {
	st := s.notebooks()
	st.mu.Lock()
	cur, err := mdLookup(st, k, "name", name)
	if err == nil && etag != "" && etag != cur.GetEtag() {
		err = apierror.FailedPrecondition("%s %s: etag %q does not match its current etag %q", k.title, name, etag, cur.GetEtag())
	}
	if err != nil {
		st.mu.Unlock()
		return nil, grpcError(err)
	}
	delete(k.get(st.meta()), name)
	k.drop(st.meta(), name)
	st.save()
	st.mu.Unlock()
	return s.finished(name, &aiplatformpb.DeleteOperationMetadata{GenericMetadata: generic()}, &emptypb.Empty{}, nil)
}

// mdPurge deletes (force) or counts the nodes passing filter, answering
// the count and, unless force, a sample of at most 100 names.
func mdPurge[T mdRes](s *Server, k *mdKind[T], parent, filter string, force bool) (int64, []string, error) {
	if strings.TrimSpace(filter) == "" {
		return 0, nil, grpcError(apierror.InvalidArgument("filter is required: a filter matching the %s to be purged", k.coll))
	}
	st := s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	if err := st.mdEnsureStore("parent", parent); err != nil {
		return 0, nil, grpcError(err)
	}
	all, err := mdSelect(st, k, parent, filter)
	if err != nil {
		return 0, nil, grpcError(err)
	}
	var sample []string
	for _, v := range all {
		if force {
			delete(k.get(st.meta()), v.GetName())
			k.drop(st.meta(), v.GetName())
		} else if len(sample) < 100 {
			sample = append(sample, v.GetName())
		}
	}
	if force && len(all) > 0 {
		st.save()
	}
	return int64(len(all)), sample, nil
}

// ---- filters

// rewriteFilter turns the documented ML Metadata filter into
// aipfilter's: metadata.KEY.TYPE_value reads metadata.fields[KEY], and
// in_context("C"), parent_contexts:"C" and child_contexts:"C" become the
// names they select. The caller holds st.mu.
func (md *mdStore) rewriteFilter(filter, coll string) (string, error) {
	bad := func(format string, a ...any) error {
		return apierror.InvalidArgument("invalid filter %q: %s", filter, fmt.Sprintf(format, a...))
	}
	var b strings.Builder
	depth := 0
	n := len(filter)
	skip := func(i int) int {
		for i < n && mdSpace(filter[i]) {
			i++
		}
		return i
	}
	// operand reads a quoted string or bare text at i.
	operand := func(i int) (string, int, error) {
		i = skip(i)
		if i < n && (filter[i] == '"' || filter[i] == '\'') {
			j := strings.IndexByte(filter[i+1:], filter[i])
			if j < 0 {
				return "", 0, bad("unterminated string at offset %d", i)
			}
			return filter[i+1 : i+1+j], i + j + 2, nil
		}
		j := i
		for j < n && !mdSpace(filter[j]) && filter[j] != ')' && filter[j] != '(' {
			j++
		}
		if j == i {
			return "", 0, bad("expected a value at offset %d", i)
		}
		return filter[i:j], j, nil
	}
	for i := 0; i < n; {
		c := filter[i]
		switch {
		case c == '"' || c == '\'':
			j := strings.IndexByte(filter[i+1:], c)
			if j < 0 {
				return "", bad("unterminated string at offset %d", i)
			}
			b.WriteString(filter[i : i+j+2])
			i += j + 2
		case c == '(':
			if depth++; depth > 5 {
				return "", bad("the maximum nested expression depth is 5")
			}
			b.WriteByte(c)
			i++
		case c == ')':
			depth--
			b.WriteByte(c)
			i++
		case c == '_' || c >= 'a' && c <= 'z' || c >= 'A' && c <= 'Z':
			j := i
			for j < n && (filter[j] == '_' || filter[j] == '.' || filter[j] >= 'a' && filter[j] <= 'z' ||
				filter[j] >= 'A' && filter[j] <= 'Z' || filter[j] >= '0' && filter[j] <= '9') {
				j++
			}
			word := filter[i:j]
			switch {
			case word == "in_context" && skip(j) < n && filter[skip(j)] == '(':
				if coll == "contexts" {
					return "", bad("in_context() filters artifacts and executions, not contexts")
				}
				ctx, k, err := operand(skip(j) + 1)
				if err != nil {
					return "", err
				}
				if k = skip(k); k >= n || filter[k] != ')' {
					return "", bad("missing \")\" after in_context(%q", ctx)
				}
				set := md.ctxArtifacts[ctx]
				if coll == "executions" {
					set = md.ctxExecutions[ctx]
				}
				b.WriteString(nameIn(sortedNames(set)))
				i = k + 1
			case (word == "parent_contexts" || word == "child_contexts") && coll == "contexts":
				k := skip(j)
				if k >= n || (filter[k] != ':' && filter[k] != '=') {
					return "", bad("%s takes the HAS operator, as in %s:\"CONTEXT\"", word, word)
				}
				ctx, k, err := operand(k + 1)
				if err != nil {
					return "", err
				}
				var names []string
				if word == "child_contexts" {
					if c := md.contexts[ctx]; c != nil {
						names = c.GetParentContexts()
					}
				} else {
					for _, cn := range sortedNames(md.contexts) {
						for _, p := range md.contexts[cn].GetParentContexts() {
							if p == ctx {
								names = append(names, cn)
							}
						}
					}
				}
				b.WriteString(nameIn(names))
				i = k
			case strings.HasPrefix(word, "metadata."):
				rest, k := word[len("metadata."):], j
				var key, typ string
				if rest == "" && k < n && filter[k] == '"' {
					e := strings.IndexByte(filter[k+1:], '"')
					if e < 0 {
						return "", bad("unterminated metadata key at offset %d", k)
					}
					key = filter[k+1 : k+1+e]
					k += e + 2
					t := k
					for t < n && (filter[t] == '.' || filter[t] == '_' || filter[t] >= 'a' && filter[t] <= 'z') {
						t++
					}
					typ = strings.TrimPrefix(filter[k:t], ".")
					k = t
				} else {
					key, typ, _ = strings.Cut(rest, ".")
				}
				switch typ {
				case "number_value", "string_value", "bool_value":
				default:
					return "", bad("a metadata filter is metadata.<field_name>.<type_value>, type_value one of number_value, string_value and bool_value")
				}
				if key == "" || strings.ContainsAny(key, ".[]\"") {
					return "", bad("metadata field name %q is not supported", key)
				}
				fmt.Fprintf(&b, "metadata.fields[%q].%s", key, typ)
				i = k
			default:
				b.WriteString(word)
				i = j
			}
		default:
			b.WriteByte(c)
			i++
		}
	}
	return b.String(), nil
}

func mdSpace(c byte) bool { return c == ' ' || c == '\t' || c == '\n' || c == '\r' }

// nameIn is a restriction true of exactly names.
func nameIn(names []string) string {
	if len(names) == 0 {
		return `name="-"`
	}
	q := make([]string, len(names))
	for i, n := range names {
		q[i] = strconv.Quote(n)
	}
	return "name=(" + strings.Join(q, " OR ") + ")"
}

