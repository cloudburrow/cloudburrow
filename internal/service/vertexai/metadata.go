func (m *metadataService) QueryArtifactLineageSubgraph(_ context.Context, req *aiplatformpb.QueryArtifactLineageSubgraphRequest) (*aiplatformpb.LineageSubgraph, error) {
	if req.GetMaxHops() < 0 {
		return nil, grpcError(apierror.InvalidArgument("max_hops must not be negative, got %d", req.GetMaxHops()))
	}
	st := m.s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	start := req.GetArtifact()
	if _, err := mdLookup(st, artifactKind, "artifact", start); err != nil {
		return nil, grpcError(err)
	}
	store, _, _ := parseMDName("artifact", "artifacts", start)
	md := st.meta()
	// pass is the artifacts the filter keeps.
	pass := map[string]bool{}
	ok, err := mdSelect(st, artifactKind, store, req.GetFilter())
	if err != nil {
		return nil, grpcError(err)
	}
	for _, a := range ok {
		pass[a.GetName()] = true
	}
	// byArtifact is the executions each artifact has an event with.
	byArtifact := map[string][]string{}
	for e, evs := range md.events {
		if !strings.HasPrefix(e, store+"/") {
			continue
		}
		for _, ev := range evs {
			byArtifact[ev.GetArtifact()] = append(byArtifact[ev.GetArtifact()], e)
		}
	}
	arts, execs := map[string]bool{start: true}, map[string]bool{}
	frontier := []string{start}
	for hop := 0; len(frontier) > 0 && (req.GetMaxHops() == 0 || hop < int(req.GetMaxHops())); hop++ {
		var next []string
		if hop%2 == 0 {
			for _, a := range frontier {
				for _, e := range byArtifact[a] {
					if !execs[e] {
						execs[e] = true
						next = append(next, e)
					}
				}
			}
		} else {
			for _, e := range frontier {
				for _, ev := range md.events[e] {
					if a := ev.GetArtifact(); !arts[a] && pass[a] {
						arts[a] = true
						next = append(next, a)
					}
				}
			}
		}
		sort.Strings(next)
		frontier = next
	}
	g, err := md.subgraph(arts, execs)
	return g, grpcError(err)
}

// ---- MetadataSchemas

func (m *metadataService) CreateMetadataSchema(_ context.Context, req *aiplatformpb.CreateMetadataSchemaRequest) (*aiplatformpb.MetadataSchema, error) {
	in := req.GetMetadataSchema()
	if in == nil {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema is required"))
	}
	if in.GetSchema() == "" {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema.schema is required"))
	}
	if len(in.GetSchema()) > mdMaxBytes {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema.schema is %d bytes; it can be at most %d bytes", len(in.GetSchema()), mdMaxBytes))
	}
	if v := in.GetSchemaVersion(); v != "" && !mdSchemaVersionRE.MatchString(v) {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema.schema_version %q must match ^[0-9]+.+.+$, such as 1.0.0", v))
	}
	var doc struct {
		Title string `yaml:"title"`
	}
	if err := yaml.Unmarshal([]byte(in.GetSchema()), &doc); err != nil {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema.schema is not a YAML OpenAPI schema object: %v", err))
	}
	id := req.GetMetadataSchemaId()
	if id == "" {
		id = uuid.NewString()
	} else if !mdIDRE.MatchString(id) {
		return nil, grpcError(apierror.InvalidArgument("metadata_schema_id %q must be 4-128 characters of lowercase letters, digits and hyphens", id))
	}
	st := m.s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	parent := req.GetParent()
	if err := st.mdEnsureStore("parent", parent); err != nil {
		return nil, grpcError(err)
	}
	name := parent + "/metadataSchemas/" + id
	md := st.meta()
	if md.schemas[name] != nil {
		return nil, grpcError(apierror.AlreadyExists("MetadataSchema %s already exists", name))
	}
	if doc.Title != "" {
		for n, s := range md.schemas {
			if strings.HasPrefix(n, parent+"/") && s.GetSchemaVersion() == in.GetSchemaVersion() && schemaTitle(s.GetSchema()) == doc.Title {
				return nil, grpcError(apierror.AlreadyExists("MetadataSchema %s already has title %q and version %q", n, doc.Title, in.GetSchemaVersion()))
			}
		}
	}
	c := proto.Clone(in).(*aiplatformpb.MetadataSchema)
	c.Name, c.CreateTime = name, timestamppb.New(st.clock())
	md.schemas[name] = c
	st.save()
	return proto.Clone(c).(*aiplatformpb.MetadataSchema), nil
}

func schemaTitle(schema string) string {
	var doc struct {
		Title string `yaml:"title"`
	}
	_ = yaml.Unmarshal([]byte(schema), &doc)
	return doc.Title
}

func (m *metadataService) GetMetadataSchema(_ context.Context, req *aiplatformpb.GetMetadataSchemaRequest) (*aiplatformpb.MetadataSchema, error) {
	if _, _, err := parseMDName("name", "metadataSchemas", req.GetName()); err != nil {
		return nil, grpcError(err)
	}
	st := m.s.notebooks()
	st.mu.Lock()
	defer st.mu.Unlock()
	s := st.meta().schemas[req.GetName()]
	if s == nil {
		return nil, grpcError(apierror.NotFound("MetadataSchema %s not found", req.GetName()))
	}
	return proto.Clone(s).(*aiplatformpb.MetadataSchema), nil
}

func (m *metadataService) ListMetadataSchemas(_ context.Context, req *aiplatformpb.ListMetadataSchemasRequest) (*aiplatformpb.ListMetadataSchemasResponse, error) {
	size, err := mdPageSize(req.GetPageSize())
	if err != nil {
		return nil, grpcError(err)
	}
	st := m.s.notebooks()
	st.mu.Lock()
	if err := st.mdEnsureStore("parent", req.GetParent()); err != nil {
		st.mu.Unlock()
		return nil, grpcError(err)
	}
	var all []*aiplatformpb.MetadataSchema
	for n, s := range st.meta().schemas {
		if strings.HasPrefix(n, req.GetParent()+"/metadataSchemas/") {
			all = append(all, proto.Clone(s).(*aiplatformpb.MetadataSchema))
		}
	}
	st.mu.Unlock()
	sortNewest(all)
	all, err = aipfilter.Apply(req.GetFilter(), all, aipfilter.Fields("name", "schema_version", "schema_type", "create_time", "description"))
	if err != nil {
		return nil, grpcError(err)
	}
	items, next, err := aipfilter.Page("metadataSchemas:"+req.GetParent()+"|"+req.GetFilter(), all, req.GetPageToken(), size)
	if err != nil {
		return nil, grpcError(err)
	}
	return &aiplatformpb.ListMetadataSchemasResponse{MetadataSchemas: items, NextPageToken: next}, nil
}

// ---- persistence

type mdSaved struct {
	Stores            []json.RawMessage   `json:"stores,omitempty"`
	Artifacts         []json.RawMessage   `json:"artifacts,omitempty"`
	Contexts          []json.RawMessage   `json:"contexts,omitempty"`
	Executions        []json.RawMessage   `json:"executions,omitempty"`
	Schemas           []json.RawMessage   `json:"schemas,omitempty"`
	Events            []json.RawMessage   `json:"events,omitempty"`
	ContextArtifacts  map[string][]string `json:"contextArtifacts,omitempty"`
	ContextExecutions map[string][]string `json:"contextExecutions,omitempty"`
}

func marshalAll[V proto.Message](m map[string]V) []json.RawMessage {
	var out []json.RawMessage
	for _, n := range sortedNames(m) {
		if b, err := protojson.Marshal(m[n]); err == nil {
			out = append(out, b)
		}
	}
	return out
}

// savedMetadata is the ML Metadata as the store's file keeps it, nil when
// there is none; the caller holds st.mu.
func (st *notebookStore) savedMetadata() json.RawMessage {
	md := st.md
	if md == nil || len(md.stores) == 0 {
		return nil
	}
	out := mdSaved{Stores: marshalAll(md.stores), Artifacts: marshalAll(md.artifacts), Contexts: marshalAll(md.contexts),
		Executions: marshalAll(md.executions), Schemas: marshalAll(md.schemas),
		ContextArtifacts: map[string][]string{}, ContextExecutions: map[string][]string{}}
	for _, e := range sortedNames(md.events) {
		for _, ev := range md.events[e] {
			if b, err := protojson.Marshal(ev); err == nil {
				out.Events = append(out.Events, b)
			}
		}
	}
	for c, set := range md.ctxArtifacts {
		if len(set) > 0 {
			out.ContextArtifacts[c] = sortedNames(set)
		}
	}
	for c, set := range md.ctxExecutions {
		if len(set) > 0 {
			out.ContextExecutions[c] = sortedNames(set)
		}
	}
	b, err := json.Marshal(out)
	if err != nil {
		return nil
	}
	return b
}

func loadAll[V proto.Message](raw []json.RawMessage, mk func() V, into map[string]V, name func(V) string) {
	for _, b := range raw {
		v := mk()
		if lenient.Unmarshal(b, v) == nil && name(v) != "" {
			into[name(v)] = v
		}
	}
}

// loadMetadata restores savedMetadata's output; the caller holds st.mu.
func (st *notebookStore) loadMetadata(raw json.RawMessage) {
	if len(raw) == 0 {
		return
	}
	var in mdSaved
	if json.Unmarshal(raw, &in) != nil {
		return
	}
	md := st.meta()
	loadAll(in.Stores, func() *aiplatformpb.MetadataStore { return &aiplatformpb.MetadataStore{} }, md.stores, (*aiplatformpb.MetadataStore).GetName)
	loadAll(in.Artifacts, func() *aiplatformpb.Artifact { return &aiplatformpb.Artifact{} }, md.artifacts, (*aiplatformpb.Artifact).GetName)
	loadAll(in.Contexts, func() *aiplatformpb.Context { return &aiplatformpb.Context{} }, md.contexts, (*aiplatformpb.Context).GetName)
	loadAll(in.Executions, func() *aiplatformpb.Execution { return &aiplatformpb.Execution{} }, md.executions, (*aiplatformpb.Execution).GetName)
	loadAll(in.Schemas, func() *aiplatformpb.MetadataSchema { return &aiplatformpb.MetadataSchema{} }, md.schemas, (*aiplatformpb.MetadataSchema).GetName)
	for _, b := range in.Events {
		ev := &aiplatformpb.Event{}
		if lenient.Unmarshal(b, ev) == nil && ev.GetExecution() != "" {
			md.events[ev.GetExecution()] = append(md.events[ev.GetExecution()], ev)
		}
	}
	for c, names := range in.ContextArtifacts {
		md.ctxArtifacts[c] = map[string]bool{}
		for _, n := range names {
			md.ctxArtifacts[c][n] = true
		}
	}
	for c, names := range in.ContextExecutions {
		md.ctxExecutions[c] = map[string]bool{}
		for _, n := range names {
			md.ctxExecutions[c][n] = true
		}
	}
}
