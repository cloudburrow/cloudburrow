package vertexai

// Vertex ML Metadata (#2205): google.cloud.aiplatform.v1.MetadataService
// over gRPC and REST, the store in which Vertex AI Pipelines records each
// run's artifacts, executions and contexts and the events joining them.
//
// Documented behaviour (the MetadataService, Artifact, Context, Execution,
// Event and MetadataSchema protos, cloud.google.com/go/aiplatform v1.127.0;
// https://cloud.google.com/vertex-ai/docs/ml-metadata/introduction,
// .../ml-metadata/tracking, .../ml-metadata/analyzing; the REST reference's
// IAM sections; docs.cloud.google.com/vertex-ai/docs/quotas; read
// 2026-11-24):
//   - every *_id is optional ("a UUID generated by the service" otherwise),
//     "4-128 characters in length. Valid characters are /[a-z][0-9]-/", a
//     taken one ALREADY_EXISTS;
//   - a project and location's "default" store is made on first use, as
//     the Vertex AI SDK and Pipelines make it;
//   - display_name "may be up to 128 Unicode characters", at most 64
//     labels, metadata at most 204,800 bytes serialized (the quotas page;
//     "should not exceed 200KB"), its top-level keys trimmed; a metadata
//     schema at most 204,800 bytes, its version matching ^[0-9]+.+.+$, its
//     title (the YAML's) and version unique in the store;
//   - the lists take page_size 1-1000 (default 100), page tokens bound to
//     the other parameters, order_by (AIP-132, ascending unless " desc"),
//     and the documented filters: name, display_name, uri (artifacts),
//     state (artifacts, executions), schema_title, create_time,
//     update_time, metadata.<field_name>.<type_value> (and
//     metadata."field:1".number_value), in_context("CONTEXT") for artifacts
//     and executions, parent_contexts:"CONTEXT" and child_contexts:"CONTEXT"
//     for contexts, combined with AND and OR to a depth of 5;
//   - an Update's etag, when set, must match (else FAILED_PRECONDITION, as
//     a Delete's etag); allow_missing creates; Delete answers an Operation;
//     Purge needs a filter and with force=false only counts and samples (at
//     most 100 names);
//   - AddContextArtifactsAndExecutions, AddContextChildren and
//     AddExecutionEvents skip what is already there; a child that would
//     make a cycle or give a context more than 10 parents is
//     INVALID_ARGUMENT; RemoveContextChildren skips non-children;
//   - the lineage queries answer a LineageSubgraph, FAILED_PRECONDITION
//     beyond 1000 artifacts, executions or events; QueryArtifactLineageSubgraph's
//     negative max_hops is INVALID_ARGUMENT, its filter keeps (and only
//     traverses) the artifacts that pass it.
//
// Local differences: max_hops 0 is read as "no value" (the transitive
// closure): proto3 cannot tell the two apart, and the store keeps no system
// schemas (system.Artifact and the like), which Vertex AI lists in every
// store but whose texts are not published.

