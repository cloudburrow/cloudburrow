// subgraph is the artifacts and executions named and the events between
// them; the caller holds st.mu.
func (md *mdStore) subgraph(arts, execs map[string]bool) (*aiplatformpb.LineageSubgraph, error) {
	out := &aiplatformpb.LineageSubgraph{}
	for _, n := range sortedNames(arts) {
		if a := md.artifacts[n]; a != nil {
			out.Artifacts = append(out.Artifacts, proto.Clone(a).(*aiplatformpb.Artifact))
		}
	}
	for _, n := range sortedNames(execs) {
		e := md.executions[n]
		if e == nil {
			continue
		}
		out.Executions = append(out.Executions, proto.Clone(e).(*aiplatformpb.Execution))
		for _, ev := range md.events[n] {
			if arts[ev.GetArtifact()] {
				out.Events = append(out.Events, proto.Clone(ev).(*aiplatformpb.Event))
			}
		}
	}
	if len(out.Artifacts) > mdMaxGraph || len(out.Executions) > mdMaxGraph || len(out.Events) > mdMaxGraph {
		return nil, apierror.FailedPrecondition("the lineage subgraph has %d artifacts, %d executions and %d events; at most %d of each can be returned",
			len(out.Artifacts), len(out.Executions), len(out.Events), mdMaxGraph)
	}
	return out, nil
}

