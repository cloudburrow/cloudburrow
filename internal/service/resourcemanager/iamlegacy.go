// QueryAuditableServices lists the auditable services of a project, a
// folder or the organization, which must exist.
func (r *Registry) QueryAuditableServices(full string) (*adminpb.QueryAuditableServicesResponse, error) {
	if full == "" {
		return nil, apierror.InvalidArgument("full_resource_name is required, such as //cloudresourcemanager.googleapis.com/projects/PROJECT")
	}
	// Any host is taken, as for queryGrantableRoles: gcloud names the
	// resource by its override's host.
	_, rest, ok := strings.Cut(strings.TrimPrefix(full, "//"), "/")
	if !ok || !strings.HasPrefix(full, "//") {
		return nil, apierror.InvalidArgument("full_resource_name %q is not a full resource name, such as //cloudresourcemanager.googleapis.com/projects/PROJECT", full)
	}
	kind, id, _ := strings.Cut(rest, "/")
	if id == "" || strings.Contains(id, "/") {
		return nil, apierror.Unimplemented("full_resource_name %q: only a project's, a folder's or the organization's auditable services are served", full)
	}
	r.mu.Lock()
	var err error
	switch kind {
	case "projects":
		_, _, err = r.roleParentLocked(rest)
	case "folders":
		_, err = r.loadFolder(rest)
	case "organizations":
		err = checkOrg(rest)
	default:
		err = apierror.Unimplemented("full_resource_name %q: only a project's, a folder's or the organization's auditable services are served", full)
	}
	r.unlock()
	if err != nil {
		return nil, err
	}
	out := &adminpb.QueryAuditableServicesResponse{}
	for _, s := range auditableServices {
		out.Services = append(out.Services, &adminpb.QueryAuditableServicesResponse_AuditableService{Name: s})
	}
	return out, nil
}

func (s *IAMAdminServer) SignBlob(_ context.Context, req *adminpb.SignBlobRequest) (*adminpb.SignBlobResponse, error) {
	//nolint:staticcheck // the deprecated method's own fields
	return wrap(s.reg.SignBlob(req.GetName(), req.GetBytesToSign()))
}

func (s *IAMAdminServer) SignJwt(_ context.Context, req *adminpb.SignJwtRequest) (*adminpb.SignJwtResponse, error) {
	//nolint:staticcheck // the deprecated method's own fields
	return wrap(s.reg.SignJwt(req.GetName(), req.GetPayload()))
}

func (s *IAMAdminServer) QueryAuditableServices(_ context.Context, req *adminpb.QueryAuditableServicesRequest) (*adminpb.QueryAuditableServicesResponse, error) {
	return wrap(s.reg.QueryAuditableServices(req.GetFullResourceName()))
}
