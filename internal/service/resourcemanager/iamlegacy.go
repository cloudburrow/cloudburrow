// maxSignJwtLifetime is how far in the future signJwt's exp may be.
const maxSignJwtLifetime = 12 * time.Hour

// legacySigner is the live, enabled account name names and its signing key.
func (r *Registry) legacySigner(name string) (*rsa.PrivateKey, string, error) {
	r.mu.Lock()
	a, err := r.findSALocked(name, false)
	r.unlock()
	if err != nil {
		return nil, "", err
	}
	if a.Disabled {
		return nil, "", apierror.FailedPrecondition("The service account %s is disabled.", a.email())
	}
	return r.ServiceAccountSigner(name)
}

// SignBlob is the IAM API's deprecated projects.serviceAccounts.signBlob.
func (r *Registry) SignBlob(name string, blob []byte) (*adminpb.SignBlobResponse, error) {
	if len(blob) == 0 {
		return nil, apierror.InvalidArgument("bytes_to_sign is required.")
	}
	key, kid, err := r.legacySigner(name)
	if err != nil {
		return nil, err
	}
	sum := sha256.Sum256(blob)
	sig, err := rsa.SignPKCS1v15(rand.Reader, key, crypto.SHA256, sum[:])
	if err != nil {
		return nil, apierror.Internal(err, "sign")
	}
	//nolint:staticcheck // the deprecated method's own fields
	return &adminpb.SignBlobResponse{KeyId: kid, Signature: sig}, nil
}

// SignJwt is the IAM API's deprecated projects.serviceAccounts.signJwt.
func (r *Registry) SignJwt(name, payload string) (*adminpb.SignJwtResponse, error) {
	if payload == "" {
		return nil, apierror.InvalidArgument("payload is required.")
	}
	var claims map[string]any
	dec := json.NewDecoder(strings.NewReader(payload))
	dec.UseNumber()
	if err := dec.Decode(&claims); err != nil || claims == nil {
		return nil, apierror.InvalidArgument("payload must be a serialized JSON object that contains a JWT Claims Set.")
	}
	now := r.now()
	if v, ok := claims["exp"]; ok {
		n, isNum := v.(json.Number)
		exp, err := n.Int64()
		if !isNum || err != nil {
			return nil, apierror.InvalidArgument("The exp claim must be an integer timestamp.")
		}
		if exp < now.Unix() {
			return nil, apierror.InvalidArgument("The exp claim must not be in the past.")
		}
		if exp > now.Add(maxSignJwtLifetime).Unix() {
			return nil, apierror.InvalidArgument("The exp claim must be no more than 12 hours in the future.")
		}
	} else {
		claims["exp"] = now.Add(time.Hour).Unix()
	}
	key, kid, err := r.legacySigner(name)
	if err != nil {
		return nil, err
	}
	head, err := json.Marshal(map[string]string{"alg": "RS256", "typ": "JWT", "kid": kid})
	if err != nil {
		return nil, apierror.Internal(err, "encode the JWT header")
	}
	body, err := json.Marshal(claims)
	if err != nil {
		return nil, apierror.Internal(err, "encode the JWT claims")
	}
	enc := base64.RawURLEncoding
	signing := enc.EncodeToString(head) + "." + enc.EncodeToString(body)
	sum := sha256.Sum256([]byte(signing))
	sig, err := rsa.SignPKCS1v15(rand.Reader, key, crypto.SHA256, sum[:])
	if err != nil {
		return nil, apierror.Internal(err, "sign")
	}
	//nolint:staticcheck // the deprecated method's own fields
	return &adminpb.SignJwtResponse{KeyId: kid, SignedJwt: signing + "." + enc.EncodeToString(sig)}, nil
}

