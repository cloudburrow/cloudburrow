//   - https://cloud.google.com/sql/pricing  (shared-core table)
//   - https://cloud.google.com/sql/docs/mysql/admin-api/rest/v1/tiers  (Tier resource)
//   - https://cloud.google.com/sql/docs/mysql/admin-api/rest/v1/tiers/list
//   - https://cloud.google.com/sql/docs/mysql/admin-api/rest/v1/operations/cancel
//   - https://cloud.google.com/sql/docs/mysql/import-export/cancel-import-export
//   - https://cloud.google.com/sql/docs/mysql/admin-api/rest/v1/instances/resetSslConfig
//   - https://cloud.google.com/sql/docs/mysql/admin-api/rest/v1/sslCerts/insert
//
// ---------------------------------------------------------------------------
// operations.cancel (sql.operations.cancel)
// ---------------------------------------------------------------------------
//
// REST: POST https://sqladmin.googleapis.com/v1/projects/{project}/operations/{operation}/cancel
// ("Cancels an instance operation that has been performed on an instance.")
// Optional query parameter `location`. Request body must be empty. On success
// the response body is an empty JSON object ({}).
//
// Which operations can be cancelled: the cancel-import-export page documents
// cancellation only for IMPORT and EXPORT operations (SQL dump or CSV). Its
// troubleshooting table lists the error
//
//	"You can't cancel operation [operation-ID] because Cloud SQL doesn't
//	 support the cancellation of an [operation-type] operation."
//
// for "an operation type other than IMPORT or EXPORT".
//
// Cancelling a DONE operation: documented error message
//
//	"You can't cancel operation [operation-ID] because this operation isn't
//	 in progress."
//
// returned when "trying to cancel an import or export operation that's
// completed, failed, or cancelled". The HTTP status / canonical error code is
// NOT documented. A third documented transient error is
//
//	"The [operation-type] operation isn't cancelled. Wait and retry in a few
//	 seconds."
//
// After a successful cancel, operations.get shows the operation with
// status "DONE" and error.errors[0] = {kind: "sql#operationError",
// code: "CANCEL_SUCCESSFUL", message: "Operation successfully cancelled"}
// (error.kind "sql#operationErrors"). For imports, "MySQL doesn't always fully
// roll back the data" (partial data may remain).
//
// ---------------------------------------------------------------------------
// instances.resetSslConfig
// ---------------------------------------------------------------------------
//
// Documented. POST https://sqladmin.googleapis.com/v1/projects/{project}/instances/{instance}/resetSslConfig
// "Deletes all client certificates and generates a new server SSL certificate
// for the instance." Empty request body; response is an Operation. Optional
// query param `mode` (enum ResetSslMode): RESET_SSL_MODE_UNSPECIFIED;
// ALL ("Refresh all TLS configs. This is the default behaviour.");
// SYNC_FROM_PRIMARY ("Refreshes the replication-related TLS configuration
// settings provided by the primary instance. Not applicable to on-premises
// replication instances.").
//
// ---------------------------------------------------------------------------
// sslCerts.insert
// ---------------------------------------------------------------------------
//
// POST https://sqladmin.googleapis.com/v1/projects/{project}/instances/{instance}/sslCerts
// "Creates an SSL certificate and returns it along with the private key and
// server certificate authority. The new certificate will not be usable until
// the instance is restarted."
// Request (SslCertsInsertRequest): {"commonName": string} — "User supplied
// name. Must be a distinct name from the other certificates for this instance."
// Response (SslCertsInsertResponse):
//
//	{
//	  "kind": "sql#sslCertsInsert",           // always
//	  "operation": { Operation },             // tracks the insert request
//	  "serverCaCert": { SslCert },            // server CA cert; "If this is missing you can
//	                                          //  force a new one to be generated by calling
//	                                          //  resetSslConfig method on instances resource."
//	  "clientCert": {                         // SslCertDetail: new client cert + private key
//	    "certInfo": { SslCert },              // public information about the cert
//	    "certPrivateKey": string              // client private key, PEM format
//	  }
//	}
//
// ---------------------------------------------------------------------------
// Notes on the data below
// ---------------------------------------------------------------------------
//
//   - Flags: only flags whose table row does not exclude PostgreSQL 17 / MySQL
//     8.4 (rows marked "Supported in PostgreSQL 18 and later", "only 9.6",
//     deprecated/renamed in 16/17, "not supported in MySQL 8.4", "removed in
//     8.4", "MySQL 9.7 and later", "5.7 only", and the deprecated slave_* /
//     master_* aliases were skipped). Type mapping: boolean -> BOOLEAN,
//     integer -> INTEGER, float/double -> FLOAT, string/enumeration -> STRING,
//     "multi-value repeated string" -> REPEATED_STRING, "flag" -> NONE.
//     MinValue/MaxValue are set only when the table gives concrete numbers;
//     a max of "varies" leaves MaxValue nil. "0 ... N, or -1" ranges are
//     recorded as -1 ... N. No flag is marked beta/preview in either table,
//     so InBeta is false throughout.
//   - Tiers: see the comment on documentedTiers.

package sqladmin

type flagDef struct {
	Name                string
	Type                string   // sqladmin v1 Flag.type enum: BOOLEAN, STRING, INTEGER, NONE, MYSQL_TIMEZONE_OFFSET, FLOAT, REPEATED_STRING
	AppliesTo           []string // e.g. "POSTGRES_17", "MYSQL_8_4"
	AllowedStringValues []string
	MinValue, MaxValue  *int64 // nil when not documented
	RequiresRestart     bool
	InBeta              bool
}

type tierDef struct {
	Tier      string
	RAM       int64 // bytes
	DiskQuota int64 // bytes
	Region    []string
}

