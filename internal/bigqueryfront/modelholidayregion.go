// The built-in holidays of HOLIDAY_REGION (#1776,
// https://docs.cloud.google.com/bigquery/docs/reference/standard-sql/bigqueryml-syntax-create-time-series#holiday_region).
//
// As documented: HOLIDAY_REGION is a STRING or ARRAY<STRING> of GLOBAL,
// the continental regions NA, JAPAC, EMEA and LAC, and 63 country codes;
// by default no holiday effect is modelled; with more than one region the
// union of their holidays is; holiday effect modelling "is only applicable
// when the time series is daily or weekly, and longer than a year", and is
// silently not used otherwise; custom holidays (modelholiday.go) of a
// region given in HOLIDAY_REGION "overwrite or supplement" its holidays,
// and of another region are modelled as a custom region's.
//
// UNVERIFIED (2026-11-18): Google's calendar is the BigQuery public
// dataset bigquery-public-data.ml_datasets.holidays_and_events_for_forecasting,
// which CloudBurrow must not query, and no openly licensed copy exists.
// The calendar here, holidaycal.tsv.gz, is generated by
// tools/bqholidays/generate.py from the MIT-licensed python-holidays 0.84
// (pinned by SHA-256 in dependencies.json, NOTICE), for 2000 through 2035:
// the countries' public holidays in English, named in CamelCase like
// Google's (NewYearsDay, not NewYear); a continental region (and GLOBAL)
// has a holiday on a date when at least half of its countries do; a
// multi-day holiday is one occurrence on its first day; every built-in
// holiday's window is 1 day on each side (the custom default). Also chosen
// here:
//   - "longer than a year" is a series whose first and last points are
//     more than 365 days apart; a series that is not, or is not daily or
//     weekly, gets no built-in holidays (its custom holidays still apply);
//   - on a weekly series a holiday is the week whose point is nearest its
//     primary date, with no days before or after;
//   - a custom holiday of a region in HOLIDAY_REGION replaces that
//     region's built-in holiday of the same holiday_name; then, for each
//     holiday_name, a built-in occurrence whose window overlaps a kept one
//     (custom first) is dropped, and a built-in holiday whose windows are
//     those of another holiday is dropped;
//   - ML.HOLIDAY_INFO answers the holidays from 30 days before the earliest
//     training point through the end of the forecast horizon.

//go:embed holidaycal.tsv.gz
var holidayCalendarGz []byte

// holidayRegions are the documented HOLIDAY_REGION values.
var holidayRegions = func() map[string]bool {
	m := map[string]bool{}
	for _, r := range strings.Fields("GLOBAL NA JAPAC EMEA LAC AE AR AT AU BE BR CA CH CL CN CO CZ DE DK DZ EC EE EG ES FI FR GB GR HK " +
		"HU ID IE IL IN IR IT JP KR LV MA MX MY NG NL NO NZ PE PH PK PL PT RO RS RU SA SE SG SI SK TH TR TW UA US VE VN ZA") {
		m[r] = true
	}
	return m
}()

var (
	holidayCalOnce sync.Once
	holidayCal     map[string][]customHoliday
)

// holidayCalendar is the built-in calendar, by region, in date order.
func holidayCalendar() map[string][]customHoliday {
	holidayCalOnce.Do(func() {
		holidayCal = map[string][]customHoliday{}
		zr, err := gzip.NewReader(bytes.NewReader(holidayCalendarGz))
		if err != nil {
			panic("bigqueryfront: holidaycal.tsv.gz: " + err.Error())
		}
		sc := bufio.NewScanner(zr)
		for sc.Scan() {
			f := strings.Split(sc.Text(), "\t")
			if len(f) != 3 {
				continue
			}
			holidayCal[f[0]] = append(holidayCal[f[0]], customHoliday{Region: f[0], Name: f[1], Date: f[2], Pre: 1, Post: 1})
		}
		for _, hs := range holidayCal {
			sort.SliceStable(hs, func(a, b int) bool { return hs[a].Date < hs[b].Date })
		}
	})
	return holidayCal
}

// parseHolidayRegions checks HOLIDAY_REGION's values.
func parseHolidayRegions(vals []string) ([]string, string) {
	if len(vals) == 0 {
		return nil, "holiday_region must have at least one region"
	}
	seen := map[string]bool{}
	var out []string
	for _, v := range vals {
		if !holidayRegions[v] {
			return nil, "Invalid holiday_region: " + v + ". It must be GLOBAL, NA, JAPAC, EMEA, LAC or one of the documented country codes"
		}
		if !seen[v] {
			seen[v] = true
			out = append(out, v)
		}
	}
	return out, ""
}

// modelHolidaysFor are the holidays of a model with HOLIDAY_REGION regions
// and custom holidays custom, from first through last (Unix microseconds),
// as documented and chosen above.
func modelHolidaysFor(regions []string, custom []customHoliday, first, last int64) []customHoliday {
	from := time.UnixMicro(first).UTC().AddDate(0, 0, -holidayMaxWindow).Format("2006-01-02")
	to := time.UnixMicro(last).UTC().Format("2006-01-02")
	given := map[string]bool{}
	window := map[string][2]int{}
	for _, h := range custom {
		given[h.Region+"\x00"+h.Name] = true
		window[h.Name] = [2]int{h.Pre, h.Post}
	}
	out := append([]customHoliday(nil), custom...)
	cal := holidayCalendar()
	var builtin []customHoliday
	for _, r := range regions {
		for _, h := range cal[r] {
			if h.Date >= from && h.Date <= to && !given[h.Region+"\x00"+h.Name] {
				builtin = append(builtin, h)
			}
		}
	}
	day := func(d string) int {
		t, _ := time.Parse("2006-01-02", d)
		return int(t.Unix() / 86400)
	}
	kept := map[string][]int{}
	for _, h := range custom {
		kept[h.Name] = append(kept[h.Name], day(h.Date))
	}
	sort.SliceStable(builtin, func(a, b int) bool { return builtin[a].Date < builtin[b].Date })
	var added []customHoliday
	for _, h := range builtin {
		if w, ok := window[h.Name]; ok {
			h.Pre, h.Post = w[0], w[1]
		}
		d, clash := day(h.Date), false
		for _, k := range kept[h.Name] {
			if d-h.Pre <= k+h.Post && k-h.Pre <= d+h.Post {
				clash = true
				break
			}
		}
		if clash {
			continue
		}
		window[h.Name] = [2]int{h.Pre, h.Post}
		kept[h.Name] = append(kept[h.Name], d)
		added = append(added, h)
	}
	// A built-in holiday whose windows are another's is dropped.
	spans := map[string]string{}
	key := func(name string) string {
		ds := append([]int(nil), kept[name]...)
		sort.Ints(ds)
		var b strings.Builder
		for _, d := range ds {
			b.WriteString(time.Unix(int64(d)*86400, 0).UTC().Format("20060102,"))
		}
		return b.String()
	}
	for _, name := range holidayNames(custom) {
		spans[key(name)] = name
	}
	drop := map[string]bool{}
	for _, name := range holidayNames(added) {
		if containsString(holidayNames(custom), name) {
			continue
		}
		k := key(name)
		if _, ok := spans[k]; ok {
			drop[name] = true
			continue
		}
		spans[k] = name
	}
	for _, h := range added {
		if !drop[h.Name] {
			out = append(out, h)
		}
	}
	sort.SliceStable(out, func(a, b int) bool {
		x, y := out[a], out[b]
		if x.Region != y.Region {
			return x.Region < y.Region
		}
		if x.Name != y.Name {
			return x.Name < y.Name
		}
		return x.Date < y.Date
	})
	return out
}

func containsString(v []string, s string) bool {
	for _, x := range v {
		if x == s {
			return true
		}
	}
	return false
}

// holidayEligible reports whether a series of frequency fq from first to
// last (Unix microseconds) models built-in holidays: daily or weekly, and
// longer than a year.
func holidayEligible(fq string, first, last int64) bool {
	return (fq == "DAILY" || fq == "WEEKLY") && last-first > 365*24*time.Hour.Microseconds()
}
