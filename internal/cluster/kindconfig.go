package cluster

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// PortMapping publishes a node port on a host port.
//
// This is the only way a browser can open a Cloud Run URL: the tunnels used
// for the SDK endpoints are `kubectl port-forward`, which cannot serve a
// gateway that routes by Host header for arbitrary services.
type PortMapping struct {
	// HostPort is the port published on the host. It must be concrete: kind
	// cannot be asked to choose one and report it back.
	HostPort int
	// NodePort is the NodePort inside the cluster.
	NodePort int
	// ListenAddress is the host address to bind. Empty means 127.0.0.1, which
	// keeps the gateway off the LAN.
	ListenAddress string
	// Protocol is TCP when empty.
	Protocol string
}

// ConfigFileName is the kind configuration CloudBurrow generates.
const ConfigFileName = "kind.yaml"

// kubeadmPatches start the controller manager and the scheduler without
// leader election (#1610), and set the kubelet's
// imagePullCredentialsVerificationPolicy to NeverVerify.
//
// The kubelet (v1.36 in kind v0.33, KubeletEnsureSecretPulledImages) records
// each image it pulls by image ID, with the repository it pulled it from.
// An image with such a record is then usable under no other name until
// the kubelet has re-verified it by pulling, and a pod that names it with
// imagePullPolicy Never fails with ErrImageNeverPull ("is not present
// with pull policy of Never") while the node holds it. So one build both
// pushed to Artifact Registry and pulled from there, and loaded into the
// cluster as dev.local/... (a build of this instance is both, as is a
// user's image they kind-load and push), stopped running as dev.local
// once a revision had pulled its Artifact Registry name (run 44709318191).
// The cluster has one tenant, the developer, so there are no other pods
// whose credentials the check protects; NeverVerify is the kubelet's
// behaviour before the check.
//
// Leader election: the cluster has one control-plane node, so there is
// nothing to elect; and a restarted one waited out its own lease from
// before the stop, about 20 s in which no Deployment made a pod and no pod
// was scheduled. The controller manager's list is the whole list, since
// kind replaces it: enable-hostpath-provisioner is the one kind sets.
const kubeadmPatches = `kubeadmConfigPatches:
  - |
    apiVersion: kubeadm.k8s.io/v1beta4
    kind: ClusterConfiguration
    controllerManager:
      extraArgs:
        - name: enable-hostpath-provisioner
          value: "true"
        - name: leader-elect
          value: "false"
    scheduler:
      extraArgs:
        - name: leader-elect
          value: "false"
  - |
    apiVersion: kubelet.config.k8s.io/v1beta1
    kind: KubeletConfiguration
    imagePullCredentialsVerificationPolicy: NeverVerify
`

// RenderConfig produces a kind cluster configuration.
//
// Only the mappings are configurable. The node image is passed to `kind
// create` as a flag and is deliberately not duplicated here, so there is one
// place it can be wrong.
func RenderConfig(mappings []PortMapping) string {
	var b strings.Builder
	b.WriteString("# Generated by CloudBurrow. Edits are overwritten on the next `up`.\n")
	b.WriteString("#\n")
	b.WriteString("# extraPortMappings are applied only when the cluster is created. Changing\n")
	b.WriteString("# them requires `cloudburrow delete` followed by `cloudburrow up`.\n")
	b.WriteString("apiVersion: kind.x-k8s.io/v1alpha4\n")
	b.WriteString("kind: Cluster\n")
	b.WriteString(kubeadmPatches)
	b.WriteString("nodes:\n")
	b.WriteString("  - role: control-plane\n")
	if len(mappings) == 0 {
		return b.String()
	}
	b.WriteString("    extraPortMappings:\n")
	for _, m := range mappings {
		listen := m.ListenAddress
		if listen == "" {
			listen = "127.0.0.1"
		}
		proto := m.Protocol
		if proto == "" {
			proto = "TCP"
		}
		fmt.Fprintf(&b, "      - containerPort: %d\n", m.NodePort)
		fmt.Fprintf(&b, "        hostPort: %d\n", m.HostPort)
		fmt.Fprintf(&b, "        listenAddress: %q\n", listen)
		fmt.Fprintf(&b, "        protocol: %s\n", proto)
	}
	return b.String()
}

// WriteConfig writes a kind configuration into dir and returns its path.
//
// It is written beside the kubeconfig rather than into a temporary file so
// that a developer debugging a cluster can see exactly what created it.
func WriteConfig(dir string, mappings []PortMapping) (string, error) {
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("create cluster config directory: %w", err)
	}
	path := filepath.Join(dir, ConfigFileName)
	if err := os.WriteFile(path, []byte(RenderConfig(mappings)), 0o644); err != nil {
		return "", fmt.Errorf("write cluster config: %w", err)
	}
	return path, nil
}
