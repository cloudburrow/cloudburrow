// TestSQLGeography runs the examples of GoogleSQL for Bigtable's geography
// reference (https://cloud.google.com/bigtable/docs/reference/sql/geography_functions,
// re-read 2026-11-17) and, for the functions it gives no example of, the
// same functions' examples in GoogleSQL's BigQuery reference
// (https://cloud.google.com/bigquery/docs/reference/standard-sql/geography_functions).
// Examples that read rows FROM UNNEST, which GoogleSQL for Bigtable's FROM
// does not take, are run one row per expression.
func TestSQLGeography(t *testing.T) {
	run, prepare := sqlFixture(t)
	poly := "ST_GEOGFROMTEXT('POLYGON((1 1, 20 1, 10 20, 1 1))')"
	pairs := [][2]string{
		// ST_CONTAINS and ST_COVERS: exterior, boundary and interior points.
		{"SELECT ST_ASTEXT(ST_GEOGPOINT(0, 0)), ST_CONTAINS(" + poly + ", ST_GEOGPOINT(0, 0)), ST_CONTAINS(" + poly + ", ST_GEOGPOINT(1, 1)), ST_CONTAINS(" + poly + ", ST_GEOGPOINT(10, 10))",
			"POINT(0 0) false false true"},
		{"SELECT ST_COVERS(" + poly + ", ST_GEOGPOINT(0, 0)), ST_COVERS(" + poly + ", ST_GEOGPOINT(1, 1)), ST_COVERS(" + poly + ", ST_GEOGPOINT(10, 10))",
			"false true true"},
		// ST_GEOGFROM's four formats.
		{"SELECT ST_ASTEXT(ST_GEOGFROM('POLYGON((0 0, 0 2, 2 2, 2 0, 0 0))'))", "POLYGON((2 0, 2 2, 0 2, 0 0, 2 0))"},
		{"SELECT ST_ASTEXT(ST_GEOGFROM(FROM_HEX('010100000000000000000000400000000000001040'))), ST_ASTEXT(ST_GEOGFROM('010100000000000000000000400000000000001040'))", "POINT(2 4) POINT(2 4)"},
		{`SELECT ST_ASTEXT(ST_GEOGFROM('{ "type": "Polygon", "coordinates": [ [ [2, 0], [2, 2], [1, 2], [0, 2], [0, 0], [2, 0] ] ] }'))`, "POLYGON((2 0, 2 2, 1 2, 0 2, 0 0, 2 0))"},
		{"SELECT ST_GEOHASH(ST_GEOGPOINT(-122.35, 47.62), 10)", "c22yzugqw7"},
		{"SELECT ST_HAUSDORFFDWITHIN(ST_GEOGFROMTEXT('LINESTRING(10 1, 20 1)'), ST_GEOGFROMTEXT('LINESTRING(10 2, 20 2)'), 100000)", "false"},
		// ST_INTERSECTSBOX of each of three points.
		{"SELECT ST_INTERSECTSBOX(ST_GEOGPOINT(10, 10), -90, 0, 90, 20), ST_INTERSECTSBOX(ST_GEOGPOINT(10, 10), 90, 0, -90, 20)", "true false"},
		{"SELECT ST_INTERSECTSBOX(ST_GEOGPOINT(170, 10), -90, 0, 90, 20), ST_INTERSECTSBOX(ST_GEOGPOINT(170, 10), 90, 0, -90, 20)", "false true"},
		{"SELECT ST_INTERSECTSBOX(ST_GEOGPOINT(30, 30), -90, 0, 90, 20), ST_INTERSECTSBOX(ST_GEOGPOINT(30, 30), 90, 0, -90, 20)", "false false"},
		// ST_MAKELINE's first three rows.
		{"SELECT ST_ASTEXT(ST_MAKELINE([ST_GEOGPOINT(1, 2), ST_GEOGPOINT(2, 3)])), ST_ASTEXT(ST_MAKELINE([ST_GEOGPOINT(1, 2), ST_GEOGPOINT(1, 2)]))", "LINESTRING(1 2, 2 3) POINT(1 2)"},
		{"SELECT ST_ASTEXT(ST_MAKELINE([ST_MAKELINE(ST_GEOGPOINT(1, 2), ST_GEOGPOINT(2, 3)), ST_MAKELINE(ST_GEOGPOINT(2, 3), ST_GEOGPOINT(3, 4)), ST_MAKELINE(ST_GEOGPOINT(3, 4), ST_GEOGPOINT(4, 5))]))", "LINESTRING(1 2, 2 3, 3 4, 4 5)"},
		{"SELECT ST_ASTEXT(ST_STARTPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 1, 3 2, 3 3)'))), ST_ASTEXT(ST_ENDPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 1, 3 2, 3 3)')))", "POINT(1 1) POINT(3 3)"},
		// BigQuery's GoogleSQL examples: measures to its documented digits.
		{"SELECT ST_HAUSDORFFDISTANCE(ST_GEOGFROMTEXT('LINESTRING(20 70, 70 60, 10 70, 70 70)'), ST_GEOGFROMTEXT('LINESTRING(20 90, 30 90, 60 10, 90 10)'), directed => TRUE)", "1.6889339832041925e+06"},
		{"SELECT ST_HAUSDORFFDISTANCE(ST_GEOGFROMTEXT('LINESTRING(20 90, 30 90, 60 10, 90 10)'), ST_GEOGFROMTEXT('LINESTRING(20 70, 70 60, 10 70, 70 70)'), directed => TRUE)", "5.802892745488612e+06"},
		{"SELECT ST_HAUSDORFFDISTANCE(ST_GEOGFROMTEXT('LINESTRING(20 70, 70 60, 10 70, 70 70)'), ST_GEOGFROMTEXT('LINESTRING(20 90, 30 90, 60 10, 90 10)'))", "5.802892745488612e+06"},
		{"SELECT ST_ANGLE(ST_GEOGPOINT(1, 0), ST_GEOGPOINT(0, 0), ST_GEOGPOINT(0, 1)), ST_ANGLE(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0), ST_GEOGPOINT(0, 1)), ST_ANGLE(ST_GEOGPOINT(1, 0), ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0))",
			"4.71238898038469 0.7854743216187385 0"},
		{"SELECT ST_ANGLE(ST_GEOGPOINT(1, 0), ST_GEOGPOINT(0, 0), ST_GEOGPOINT(0, 0)), ST_ANGLE(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(-30, 0), ST_GEOGPOINT(150, 0)), ST_ANGLE(ST_GEOGPOINT(0, 0), NULL, NULL)", "NULL NULL NULL"},
		{"SELECT ST_AZIMUTH(ST_GEOGPOINT(1, 0), ST_GEOGPOINT(0, 0)), ST_AZIMUTH(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0)), ST_AZIMUTH(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(0, 1))", "4.71238898038469 1.5707963267948966 0"},
		{"SELECT ST_AZIMUTH(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(0, 0)), ST_AZIMUTH(ST_GEOGPOINT(-30, 0), ST_GEOGPOINT(150, 0))", "NULL NULL"},
		// ST_BOUNDINGBOX, ST_EXTERIORRING, ST_DUMP.
		{"SELECT ST_BOUNDINGBOX(ST_GEOGFROMTEXT('POLYGON((-125 48, -124 46, -117 46, -117 49, -125 48))')), ST_BOUNDINGBOX(ST_GEOGFROMTEXT('POINT EMPTY'))", "(-125,46,-117,49) NULL"},
		{"SELECT ST_BOUNDINGBOX(ST_GEOGFROMTEXT('POLYGON((172 53, -130 55, -141 70, 172 53))')), ST_BOUNDINGBOX(ST_GEOGFROMTEXT('POLYGON((172 53, -141 70, -130 55, 172 53))', oriented => TRUE))", "(172,53,230,70) (-180,-90,180,90)"},
		{"SELECT ST_ASTEXT(ST_EXTERIORRING(ST_GEOGFROMTEXT('POLYGON((0 0, 1 4, 2 2, 0 0))'))), ST_ASTEXT(ST_EXTERIORRING(ST_GEOGFROMTEXT('POLYGON((1 1, 1 10, 5 10, 5 1, 1 1), (2 2, 3 4, 2 4, 2 2))')))",
			"LINESTRING(2 2, 1 4, 0 0, 2 2) LINESTRING(5 1, 5 10, 1 10, 1 1, 5 1)"},
		{"SELECT ARRAY_LENGTH(ST_DUMP(ST_GEOGFROMTEXT('MULTIPOINT(0 0, 1 1)'))), ST_ASTEXT(ST_DUMP(ST_GEOGFROMTEXT('GEOMETRYCOLLECTION(POINT(0 0), LINESTRING(1 2, 2 1))'))[OFFSET(1)]), ARRAY_LENGTH(ST_DUMP(ST_GEOGFROMTEXT('GEOMETRYCOLLECTION(POINT(0 0), LINESTRING(1 2, 2 1))'), 1))",
			"2 LINESTRING(1 2, 2 1) 1"},
		// ST_LINEINTERPOLATEPOINT, ST_LINELOCATEPOINT and ST_LINESUBSTRING.
		{"SELECT ST_ASTEXT(ST_LINEINTERPOLATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), 0)), ST_ASTEXT(ST_LINEINTERPOLATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), 0.5)), ST_ASTEXT(ST_LINEINTERPOLATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), 1))",
			"POINT(1 1) POINT(2.99633827268976 3.00182528336078) POINT(5 5)"},
		{"SELECT ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(0, 0)), ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(1, 0)), ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(1, 1))",
			"0 0 0"},
		// The reference prints 0.25015214685147907, 0.5002284283637185 and
		// 0.7501905913884388: S2's projection here agrees within 5e-16.
		{"SELECT ROUND(ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(2, 2)), 15), ROUND(ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(3, 3)), 15), ROUND(ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(4, 4)), 15)",
			"0.250152146851479 0.500228428363718 0.750190591388438"},
		{"SELECT ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(5, 5)), ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), ST_GEOGPOINT(6, 5)), ST_LINELOCATEPOINT(ST_GEOGFROMTEXT('LINESTRING(1 1, 5 5)'), NULL)",
			"1 1 NULL"},
		{"SELECT ST_ASTEXT(ST_LINESUBSTRING(ST_GEOGFROMTEXT('LINESTRING(20 70, 70 60, 10 70, 70 70)'), 0.5, 1)), ST_ASTEXT(ST_LINESUBSTRING(ST_GEOGFROMTEXT('LINESTRING(20 70, 70 60, 10 70, 70 70)'), 0.5, 0.5))",
			"LINESTRING(49.4760661523471 67.2419539103851, 10 70, 70 70) POINT(49.4760661523471 67.2419539103851)"},
		{"SELECT ST_ASTEXT(ST_CONVEXHULL(ST_GEOGFROMTEXT('MULTIPOINT(2 11, 4 12, 0 15, 1 9, 1 12)'))), ST_ASTEXT(ST_GEOGFROMTEXT('MULTIPOINT(2 11, 4 12, 0 15, 1 9, 1 12)'))",
			"POLYGON((1 9, 4 12, 0 15, 1 9)) MULTIPOINT(1 9, 4 12, 2 11, 1 12, 0 15)"},
		{"SELECT ST_ASTEXT(ST_CONVEXHULL(ST_GEOGFROMTEXT('POINT(1 1)'))), ST_ASTEXT(ST_CONVEXHULL(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 2)')))",
			"POINT(0.999999999999943 1) LINESTRING(2 2, 1.49988573656168 1.5000570914792, 1 1)"},
		// S2 cell IDs.
		{"SELECT S2_CELLIDFROMPOINT(ST_GEOGPOINT(-122, 47)), S2_CELLIDFROMPOINT(ST_GEOGPOINT(-122, 47), level => 10)", "6093613931972369317 6093613287902019584"},
		{"SELECT S2_COVERINGCELLIDS(ST_GEOGPOINT(-122, 47), min_level => 12), S2_COVERINGCELLIDS(ST_GEOGFROMTEXT('POINT EMPTY'), min_level => 12)", "[6093613931972369317] []"},
		{"SELECT S2_COVERINGCELLIDS(ST_GEOGFROMTEXT('LINESTRING(-122.12 47.67, -122.19 47.69)'), min_level => 12)",
			"[6093384954555662336,6093390709811838976,6093390735581642752,6093390740145045504,6093390791416217600,6093390812891054080,6093390817187069952,6093496378892222464]"},
		// Accessors.
		{"SELECT ST_GEOMETRYTYPE(ST_GEOGFROMTEXT('MULTIPOINT(0 0, 1 1)')), ST_GEOMETRYTYPE(ST_GEOGFROMTEXT('POINT EMPTY')), ST_DIMENSION(ST_GEOGFROMTEXT('POINT EMPTY')), ST_ISEMPTY(ST_GEOGFROMTEXT('GEOMETRYCOLLECTION EMPTY'))",
			"ST_MultiPoint ST_GeometryCollection -1 true"},
		{"SELECT ST_NUMPOINTS(ST_GEOGFROMTEXT('POLYGON((0 0, 1 0, 0 1, 0 0))')), ST_NUMGEOMETRIES(ST_GEOGFROMTEXT('GEOMETRYCOLLECTION(POINT(0 0), LINESTRING(1 2, 2 1))')), ST_X(ST_GEOGPOINT(-122.35, 47.62)), ST_Y(ST_GEOGPOINT(-122.35, 47.62))",
			"4 2 -122.35 47.62"},
		{"SELECT ST_ASTEXT(ST_POINTN(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 1, 3 2, 3 3)'), -1)), ST_ISCLOSED(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 1, 1 2, 1 1)')), ST_ISRING(ST_GEOGFROMTEXT('LINESTRING(1 1, 2 1, 1 2, 1 1)'))",
			"POINT(3 3) true true"},
		// Measures on a sphere of S2's mean Earth radius, 6,371,010 m.
		{"SELECT ROUND(ST_DISTANCE(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0)), 6), ROUND(ST_LENGTH(ST_GEOGFROMTEXT('LINESTRING(0 0, 1 0)')), 6), ST_DWITHIN(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0), 111196), ST_DWITHIN(ST_GEOGPOINT(0, 0), ST_GEOGPOINT(1, 0), 111194)",
			"111195.101177 111195.101177 true false"},
		{"SELECT ST_DISTANCE(" + poly + ", ST_GEOGPOINT(10, 10)), ST_AREA(ST_GEOGPOINT(1, 1)), ST_LENGTH(" + poly + ")", "0 0 0"},
		// Errors and refusals that return NULL.
		{"SELECT ST_ASTEXT(NULL), ST_DISTANCE(ST_GEOGFROMTEXT('POINT EMPTY'), ST_GEOGPOINT(0, 0))", "NULL NULL"},
	}
	for _, p := range pairs {
		if got := joined(run(p[0], nil, nil)); got != p[1] {
			t.Errorf("%s =\n%s\nwant\n%s", p[0], got, p[1])
		}
	}
	for sql, want := range map[string]string{
		"SELECT ST_GEOGPOINT(1, 2)":                                                         "Returning expressions of type GEOGRAPHY is not allowed",
		"SELECT ST_BUFFER(ST_GEOGPOINT(1, 2), 50)":                                          "UNIMPLEMENTED",
		"SELECT ST_ASTEXT(ST_UNION_AGG(ST_GEOGPOINT(1, 2)))":                                "UNIMPLEMENTED",
		"SELECT ST_CLUSTERDBSCAN(ST_GEOGPOINT(1, 2), 1e5, 1) OVER ()":                       "not in GoogleSQL for Bigtable",
		"SELECT ST_ASTEXT(ST_GEOGPOINT(1, 91))":                                             "latitude",
		"SELECT ST_ASTEXT(ST_GEOGFROMTEXT('POINT(1 2)', oriented => TRUE, planar => TRUE))": "oriented and planar",
		"SELECT ST_GEOGPOINT(1, 2) = ST_GEOGPOINT(1, 2)":                                    "No matching signature for operator =",
		"SELECT S2_CELLIDFROMPOINT(ST_GEOGPOINT(1, 2), level => 31)":                        "level must be in [0, 30]",
		"SELECT S2_CELLIDFROMPOINT(ST_GEOGFROMTEXT('LINESTRING(1 2, 3 4)'))":                "single point",
		"SELECT ST_DISTANCE(ST_GEOGPOINT(1, 2), ST_GEOGPOINT(1, 2), use_spheroid => TRUE)":  "UNIMPLEMENTED",
	} {
		err := prepare(sql)
		if err == nil {
			t.Errorf("%s: no error, want %q", sql, want)
			continue
		}
		if want == "UNIMPLEMENTED" {
			if status.Code(err) != codes.Unimplemented {
				t.Errorf("%s: %v, want UNIMPLEMENTED", sql, err)
			}
			continue
		}
		if !strings.Contains(err.Error(), want) {
			t.Errorf("%s: %v, want %q", sql, err, want)
		}
	}
}
