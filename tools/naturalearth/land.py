# Writes internal/console/assets/vendor/naturalearth/land-110m.js, the base
# map of BigQuery Studio's Map visualization (#2094), from Natural Earth's
# public-domain ne_110m_land.geojson (third_party/naturalearth/PROVENANCE.md):
# each polygon's rings as [longitude, latitude] pairs rounded to 0.1 degree,
# as a script that sets window.CB_NATURAL_EARTH_LAND (the console serves
# scripts, and its content security policy runs only its own).
#
#   python3 -I tools/naturalearth/land.py ne_110m_land.geojson internal/console/assets/vendor/naturalearth/land-110m.js
import json
import sys

src = json.load(open(sys.argv[1], encoding="utf-8"))
rings = []
for feature in src["features"]:
    geom = feature["geometry"]
    polys = geom["coordinates"] if geom["type"] == "MultiPolygon" else [geom["coordinates"]]
    for poly in polys:
        for ring in poly:
            pts = []
            for lon, lat in ring:
                p = [round(lon, 1), round(lat, 1)]
                if not pts or pts[-1] != p:
                    pts.append(p)
            if len(pts) >= 4:
                rings.append(pts)
with open(sys.argv[2], "w", encoding="utf-8") as out:
    out.write("// Natural Earth ne_110m_land v5.1.2, public domain (third_party/naturalearth).\n")
    out.write("// Generated by tools/naturalearth/land.py; do not edit.\n")
    out.write("window.CB_NATURAL_EARTH_LAND = ")
    json.dump(rings, out, separators=(",", ":"))
    out.write(";\n")
